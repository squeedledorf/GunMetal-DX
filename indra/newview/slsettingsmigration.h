#ifndef SL_SETTINGSMIGRATION_H
#define SL_SETTINGSMIGRATION_H

#include <map>
#include <string>

class LLControlGroup;

// The old -> new names live in app_settings/settings_renames.xml (generated by
// scripts/rename_126/rename_alchemy.py). The old names are no longer declared, so a
// user file still carrying them loads them as unknown controls (kept and saved again,
// CHOP-962 -- which also keeps a downgrade working); the migration reads the user file
// itself and sets the new controls, then hides the old ones from the debug settings.
namespace SLSettingsMigration
{
    // Marker control (U32) in gSavedSettings and gSavedPerAccountSettings: the version of
    // the renames table this settings file has been migrated with.
    extern const char* const MARKER;
    constexpr unsigned VERSION = 1;

    // Old name -> new name (loaded once).
    const std::map<std::string, std::string>& renames();

    // A user settings file (global user_settings/settings.xml or an account's
    // settings_per_account.xml) just loaded into `group`: carry every value saved under an
    // old name over to its new name, unless the file has the new name too or the new
    // setting is no longer at its default. Done once per file (MARKER). Returns how many
    // values were carried over.
    unsigned migrateSettingsFile(LLControlGroup& group, const std::string& filename);

    void migrateNearbyChatOverlay(LLControlGroup& group, const std::string& filename);

    // <GMDX> Once per install, after migrateNearbyChatOverlay: the nearby chat overlay becomes the
    // GunMetal-DX chat log (NearbyChatOverlayStyle "gmdx"), whatever style the profile had.
    void migrateGMDXChatLog(LLControlGroup& group);
    // <GMDX> Once per install: the mouselook hint and coordinates go (they are off by default now).
    void migrateGMDXMouselookHud(LLControlGroup& group);

    // Once per install: an existing user file keeps what its combined per-type notification
    // modes and the SlipstreamFlashTaskbarOn* settings did, now as separate flash, taskbar
    // and show settings. A new user gets the new defaults.
    void migrateChatNotifications(LLControlGroup& group, const std::string& filename);

    // A saved preset (graphics / camera) just loaded into `group`: apply the values it
    // carries under old names to the new names. Every time the preset is loaded (the
    // file is rewritten with the new names the next time it is saved).
    unsigned migratePresetFile(LLControlGroup& group, const std::string& filename);
}

#endif // SL_SETTINGSMIGRATION_H
