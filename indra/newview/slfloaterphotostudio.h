/**
 * Photo Studio (F1): a shared top bar -- Looks, Save/Revert, Undo/Redo/History,
 * Find, and how many panels -- over one, two or four panels, each showing the
 * section its dropdown picks (see SLPhotoStudioSlot). The layout and every
 * panel's section are remembered (SLPhotoStudioLayout, SLPhotoStudioPanels).
 *
 * What lives here rather than in a panel is what there is one of however
 * many panels show it: the undo stack, the Looks bar, the frozen day cycle's
 * restore point, the white balance picker, Find and its catalog, and which
 * panels are out in windows of their own.
 */
class SLFloaterPhotoStudio final : public LLFloater
{
public:
    static constexpr S32 MAX_SLOTS = 4;

    SLFloaterPhotoStudio(const LLSD& key);
    ~SLFloaterPhotoStudio() override;

    bool postBuild() override;
    void onOpen(const LLSD& key) override;
    void onClose(bool app_quitting) override;
    void draw() override;
    void reshape(S32 width, S32 height, bool called_from_parent = true) override;
    /// Ctrl+Z / Ctrl+Y (and Ctrl+Shift+Z) step the grade's undo stack,
    /// Ctrl+F goes to Find and Ctrl+1..4 to a panel's dropdown. Floater-local:
    /// a global Ctrl+Z would fire while the user is typing anywhere.
    bool handleKeyHere(KEY key, MASK mask) override;
    /// The undo and panel keys, for this floater and its popped-out windows.
    bool handleStudioKey(KEY key, MASK mask);

    /// The open Photo Studio, or null.
    static SLFloaterPhotoStudio* findInstance();

    // --- For the section panels ---

    /// Reset one setting, as one named undo step.
    void resetSetting(const std::string& key, const std::string& caption);
    /// Reset several, as one named undo step ("Reset Bloom").
    void resetSettings(const std::set<std::string>& keys, const std::string& title);
    /// Arm the scene picker; the click that follows sets Temperature and Tint.
    void pickWhiteBalance();
    /// A section switch moved: say how many are off in the title.
    void refreshBypassTitle();

    /// The day cycle row's state, the same for every panel showing it.
    struct DayCycleState
    {
        bool mCanChange = false;
        bool mFrozen = false;
        bool mHasDay = false;
        bool mCloudsPaused = false;
        F32  mPosition = 0.f;
        /// Sunrise, noon, sunset, midnight.
        std::array<bool, 4> mPresent = { { false, false, false, false } };
    };
    /// Worked out at most once a frame.
    const DayCycleState& getDayCycleState();
    void setDayFrozen(bool frozen);
    void scrubDay(F32 position);
    void goToDayPreset(const std::string& which);
    void restoreEnvironment();

    // --- For the Effects page (FX uniforms and techniques are not settings) ---

    /// History names for an effect's uniform and a technique's switch. The
    /// "fx:" prefix keeps them apart from every gSavedSettings name.
    static std::string fxUniformKey(const std::string& effect_path, const std::string& uniform);
    static std::string fxTechniqueKey(const std::string& technique);
    /// Record an Effects page change as an undo step; @a caption is what the
    /// history calls it ("Clarity.fx: Strength"). Drags coalesce like a
    /// setting's.
    void recordEffectChange(const std::string& key, const std::string& caption, const LLSD& before, const LLSD& after);
    /// Several changes as one step ("Reset Clarity.fx").
    void beginHistoryGroup(const std::string& label);
    void endHistoryGroup();

    /// What a setting is called, and the title of the section it is in, from
    /// the catalog of every page (built the first time it is wanted).
    std::string captionFor(const std::string& key);
    std::string sectionTitleFor(const std::string& key);

    // --- For the panels ---

    void onSlotSectionChanged(S32 index, const std::string& id);
    void popOut(S32 index);
    void putBack(S32 index);
    /// A popped-out window closed.
    void onPaneClosed(S32 index, const std::string& id);
    const std::string& getSlotSection(S32 index) const;
    bool isClosing() const { return mClosing; }

    // --- For the history window ---

    const SLGradeHistory& getHistory() const { return mHistory; }
    struct HistoryRow
    {
        std::string mWhat;
        std::string mWhere;
    };
    /// Row 0 is the start of the history; row n is step n. The rows in force
    /// are 0 .. getHistory().cursor().
    std::vector<HistoryRow> getHistoryRows();
    /// Undo or redo, a step at a time, until @a cursor steps are in force.
    void goToHistory(size_t cursor);

private:
    /// What Find searches and the history names steps by: every section and
    /// setting on every page, read once from throwaway section panels.
    struct CatalogSection
    {
        std::string mPage;
        std::string mName;
        std::string mTitle;
    };
    struct CatalogSetting
    {
        std::string mKey;
        std::string mCaption;
        size_t      mSection = 0;
    };
    void buildCatalog();
    const CatalogSetting* catalogSetting(const std::string& key);

    void onFind();
    void runFind(const std::string& text);
    /// The panel Find works in: the one that last had the keyboard, else the
    /// first one shown in this window.
    SLPhotoStudioSlot* findTargetSlot();

    void setLayout(S32 count);
    void arrangeSlots();
    /// The floater's smallest size for the layout, growing it if need be.
    void applyMinimumSize();
    void loadState();
    void saveState();

    void onGradeSettingChanged(const std::string& name, const LLSD& before, const LLSD& after);
    /// Step the history one transaction and write the values back.
    bool applyHistory(bool redo_direction);
    /// Write back an Effects page change; false if @a key is not one.
    bool applyEffectChange(const std::string& key, const LLSD& value);
    void refreshHistoryButtons();
    void openHistory();

    void onWhiteBalancePicked(const LLColor3& sample);

    void onLookSelected();
    void onClickLookSave();
    void onClickLookSaveAs();
    void onClickLookDelete();
    void onClickLookRevert();
    void refreshLooksBar();

    // Day cycle. Nothing here pauses a clock, because there is no clock to
    // pause: the cycle position is computed from wall time every frame.
    // Freezing samples the running cycle at one position and installs the
    // result as a *fixed* local environment, which is what stops the motion
    // (the same move @setenv_daytime and the day cycle editor make).
    std::shared_ptr<LLSettingsDay> getScrubbableDay() const;
    bool isSkyFrozen() const;
    void applyDayPosition(F32 position);
    void freezeSkyAt(F32 position);
    void thawSky();
    void refreshDayLandmarks();

    // --- Panels ---
    LLPanel* mSlotsArea = nullptr;
    std::array<SLPhotoStudioSlot*, MAX_SLOTS> mSlots = { { nullptr, nullptr, nullptr, nullptr } };
    std::array<std::string, MAX_SLOTS> mSlotSections;
    std::array<bool, MAX_SLOTS> mSlotPoppedOut = { { false, false, false, false } };
    S32 mLayout = MAX_SLOTS;
    S32 mLastFocusedSlot = -1;
    bool mClosing = false;
    bool mPanesOpened = false;

    // --- Top bar ---
    LLComboBox* mLayoutCombo = nullptr;
    LLLineEditor* mFindEditor = nullptr;
    LLTextBox* mFindStatus = nullptr;
    LLComboBox* mLooksCombo = nullptr;
    LLUICtrl* mLookSave = nullptr;
    LLUICtrl* mLookDelete = nullptr;
    LLUICtrl* mLookRevert = nullptr;
    LLUICtrl* mUndoButton = nullptr;
    LLUICtrl* mRedoButton = nullptr;
    S32 mHistoryButtonState = -1;
    U32 mBypassTitleMask = ~0u;
    std::string mBaseTitle;
    boost::signals2::scoped_connection mLooksListConnection;
    boost::signals2::scoped_connection mLooksActiveConnection;

    /// What the history calls each Effects page change it holds.
    std::map<std::string, std::string> mFxCaptions;

    // --- Find ---
    bool mCatalogBuilt = false;
    std::vector<CatalogSection> mCatalogSections;
    std::vector<CatalogSetting> mCatalogSettings;
    std::string mLastFindText;
    size_t mLastFindIndex = 0;

    // --- Undo ---
    // A member, so it lives and dies with the floater: close Photo Studio and
    // the stack is gone. The alternative is a stack that outlives the window
    // it belongs to and silently rewrites settings a much later session is
    // editing.
    SLGradeHistory mHistory;
    std::vector<boost::signals2::scoped_connection> mHistoryConnections;
    /// Set while applyHistory writes settings, whose signals would otherwise
    /// record the undo on the stack it came from.
    bool mApplyingHistory = false;

    // --- Day cycle ---
    DayCycleState mDayState;
    U32 mDayStateFrame = 0;
    bool mDayStateValid = false;
    std::shared_ptr<LLSettingsDay> mLandmarkDay;
    SLDayCycleLandmarks::Landmarks mDayLandmarks;
    /// What ENV_LOCAL held before we froze it, so unticking Freeze gives a
    /// Personal Lighting sky back instead of dropping to the region default.
    std::shared_ptr<LLSettingsDay> mPreFreezeDay;
    std::shared_ptr<LLSettingsSky> mPreFreezeSky;
    std::shared_ptr<LLSettingsWater> mPreFreezeWater;
    /// Whole seconds: LLSettingsDay::Seconds is S32Seconds.
    S32 mPreFreezeDayLength = 0;
    S32 mPreFreezeDayOffset = 0;
    /// Whether the fixed sky in place is one we installed.
    bool mDayFreezeIsOurs = false;
};

/**
 * A Photo Studio panel in a window of its own. Keyed by the panel's index;
 * closing it puts the panel back in Photo Studio's grid.
 */
class SLFloaterPhotoStudioPane final : public LLFloater
{
public:
    SLFloaterPhotoStudioPane(const LLSD& key);
    bool postBuild() override;
    void onClose(bool app_quitting) override;
    /// Ctrl+Z / Ctrl+Y reach Photo Studio's undo from here too.
    bool handleKeyHere(KEY key, MASK mask) override;

    S32 getIndex() const { return mIndex; }
    /// The panel's section changed: retitle.
    void refreshTitle();
    SLPhotoStudioSlot* getSlot() const { return mSlot; }

private:
    S32 mIndex = 0;
    SLPhotoStudioSlot* mSlot = nullptr;
};

/**
 * Photo Studio's undo stack as a list. Double-click a step to go to it.
 */
class SLFloaterPhotoStudioHistory final : public LLFloater
{
public:
    SLFloaterPhotoStudioHistory(const LLSD& key);
    bool postBuild() override;
    void draw() override;

private:
    void fill();
    void goToSelected();

    LLScrollListCtrl* mList = nullptr;
    LLView* mEmpty = nullptr;
    U32 mRevision = ~0u;
    size_t mCursor = ~size_t(0);
};

#endif // SL_FLOATERPHOTOSTUDIO_H
