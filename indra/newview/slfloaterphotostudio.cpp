bool SLFloaterPhotoStudio::postBuild()
{
    mBaseTitle = getTitle();
    mSlotsArea = getChild<LLPanel>("slots_area");
    mLayoutCombo = getChild<LLComboBox>("layout_combo");
    mFindEditor = getChild<LLLineEditor>("find_editor");
    mFindStatus = getChild<LLTextBox>("find_status");

    mLookSave = findChild<LLUICtrl>("look_save");
    mLookDelete = findChild<LLUICtrl>("look_delete");
    mLookRevert = findChild<LLUICtrl>("look_revert");
    mLooksCombo = getChild<LLComboBox>("looks_combo");
    mLooksListConnection = LLPresetsManager::instance().setPresetListChangeLooksCallback(
        std::bind(&SLFloaterPhotoStudio::refreshLooksBar, this));
    mLooksActiveConnection = gSavedSettings.getControl("PresetLooksActive")->getSignal()->connect(
        [this](LLControlVariable*, const LLSD&, const LLSD&) { refreshLooksBar(); });
    refreshLooksBar();

    mUndoButton = findChild<LLUICtrl>("look_undo");
    mRedoButton = findChild<LLUICtrl>("look_redo");

    // Undo watches exactly the settings a Look carries. Sharing that list is
    // the point: a control worth saving is a control worth undoing. The
    // signal hands over the old value as well as the new one, and llcontrol
    // only fires it when the value really changed.
    std::vector<std::string> looks_controls;
    LLPresetsManager::instance().getLooksControlNames(looks_controls);
    for (const std::string& setting : looks_controls)
    {
        LLControlVariable* controlp = gSavedSettings.getControl(setting);
        if (!controlp)
        {
            continue;
        }
        mHistoryConnections.emplace_back(controlp->getSignal()->connect(
            [this, setting](LLControlVariable*, const LLSD& new_value, const LLSD& old_value)
            { onGradeSettingChanged(setting, old_value, new_value); }));
    }

    loadState();

    for (S32 i = 0; i < MAX_SLOTS; ++i)
    {
        SLPhotoStudioSlot* slot = new SLPhotoStudioSlot(this, i, false);
        slot->build();
        slot->setFollows(FOLLOWS_NONE);
        mSlotsArea->addChild(slot);
        mSlots[i] = slot;
        // A panel that was out last time shows its note here; its window is
        // opened with the floater (onOpen).
        if (mSlotPoppedOut[i])
        {
            slot->setPoppedOut(true);
            slot->setSection(mSlotSections[i]);
        }
    }
    // Builds the sections of the panels the layout shows.
    setLayout(mLayout);

    refreshBypassTitle();
    return LLFloater::postBuild();
}

void SLFloaterPhotoStudio::onOpen(const LLSD& key)
{
    LLFloater::onOpen(key);

    // The panels that were out last time come out again. Here rather than in
    // postBuild: the windows find this floater through the registry, which
    // only knows it once it has been built.
    if (!mPanesOpened)
    {
        mPanesOpened = true;
        for (S32 i = 0; i < mLayout; ++i)
        {
            if (mSlotPoppedOut[i])
            {
                LLFloaterReg::showInstance(PANE_FLOATER_NAME, LLSD(i), false);
            }
        }
    }
}

void SLFloaterPhotoStudio::onClose(bool app_quitting)
{
    // Remembered as they are now, popped-out panels included: closing their
    // windows below must not read as the user putting them back.
    mClosing = true;
    saveState();

    for (S32 i = 0; i < MAX_SLOTS; ++i)
    {
        if (LLFloater* pane = LLFloaterReg::findInstance(PANE_FLOATER_NAME, LLSD(i)))
        {
            pane->closeFloater(app_quitting);
        }
    }
    if (LLFloater* history = LLFloaterReg::findInstance(HISTORY_FLOATER_NAME))
    {
        history->closeFloater(app_quitting);
    }

    LLFloater::onClose(app_quitting);
}

void SLFloaterPhotoStudio::draw()
{
    refreshHistoryButtons();
    if (mBypassTitleMask != LLPipeline::sGradeBypassMask)
    {
        refreshBypassTitle();
    }

    // Which panel Find works in: the last one that had the keyboard, whether
    // here or out in a window of its own.
    if (gFocusMgr.getKeyboardFocus())
    {
        for (S32 i = 0; i < MAX_SLOTS; ++i)
        {
            if (mSlots[i] && i < mLayout && !mSlotPoppedOut[i] && mSlots[i]->hasKeyboardFocusInside())
            {
                mLastFocusedSlot = i;
                break;
            }
            if (mSlotPoppedOut[i])
            {
                SLFloaterPhotoStudioPane* pane =
                    LLFloaterReg::findTypedInstance<SLFloaterPhotoStudioPane>(PANE_FLOATER_NAME, LLSD(i));
                if (pane && pane->getSlot() && pane->getSlot()->hasKeyboardFocusInside())
                {
                    mLastFocusedSlot = i;
                    break;
                }
            }
        }
    }

    LLFloater::draw();
}

void SLFloaterPhotoStudio::reshape(S32 width, S32 height, bool called_from_parent)
{
    LLFloater::reshape(width, height, called_from_parent);
    arrangeSlots();
}

bool SLFloaterPhotoStudio::handleKeyHere(KEY key, MASK mask)
{
    if (handleStudioKey(key, mask))
    {
        return true;
    }
    return LLFloater::handleKeyHere(key, mask);
}

bool SLFloaterPhotoStudio::handleStudioKey(KEY key, MASK mask)
{
    SLKeyCommands& key_commands = SLKeyCommands::instance();
    if (key_commands.matches("photo_undo", key, mask))
    {
        applyHistory(false);
        return true;
    }
    if (key_commands.matches("photo_redo", key, mask) || key_commands.matches("photo_redo_alt", key, mask))
    {
        applyHistory(true);
        return true;
    }
    if (key_commands.matches("find_in_floater", key, mask) && mFindEditor)
    {
        if (isMinimized())
        {
            setMinimized(false);
        }
        setFrontmost(true);
        mFindEditor->setFocus(true);
        mFindEditor->selectAll();
        return true;
    }
    if (key >= '1' && key <= '4' && mask == MASK_CONTROL)
    {
        const S32 index = key - '1';
        if (index >= mLayout)
        {
            return true;
        }
        if (mSlotPoppedOut[index])
        {
            if (SLFloaterPhotoStudioPane* pane =
                    LLFloaterReg::findTypedInstance<SLFloaterPhotoStudioPane>(PANE_FLOATER_NAME, LLSD(index)))
            {
                pane->setFrontmost(true);
                if (pane->getSlot())
                {
                    pane->getSlot()->focusSectionCombo();
                }
            }
        }
        else if (mSlots[index])
        {
            mSlots[index]->focusSectionCombo();
        }
        mLastFocusedSlot = index;
        return true;
    }
    return false;
}

// --- Layout and state -------------------------------------------------------

void SLFloaterPhotoStudio::loadState()
{
    const S32 layout = gSavedSettings.getS32("SLPhotoStudioLayout");
    mLayout = (layout == 1 || layout == 2) ? layout : MAX_SLOTS;

    const LLSD panels = gSavedSettings.getLLSD("SLPhotoStudioPanels");
    if (panels.isArray())
    {
        for (S32 i = 0; i < MAX_SLOTS && i < (S32)panels.size(); ++i)
        {
            const LLSD& entry = panels[i];
            const std::string id = entry["section"].asString();
            if (SLPhotoStudioSections::find(id))
            {
                mSlotSections[i] = id;
            }
            mSlotPoppedOut[i] = entry["popped"].asBoolean();
        }
    }
    // A panel the layout does not show is not out in a window either: only
    // shown panels get their windows back when the floater opens.
    for (S32 i = mLayout; i < MAX_SLOTS; ++i)
    {
        mSlotPoppedOut[i] = false;
    }
}

void SLFloaterPhotoStudio::saveState()
{
    LLSD panels = LLSD::emptyArray();
    for (S32 i = 0; i < MAX_SLOTS; ++i)
    {
        LLSD entry;
        entry["section"] = mSlotSections[i];
        entry["popped"] = mSlotPoppedOut[i];
        panels.append(entry);
    }
    gSavedSettings.setLLSD("SLPhotoStudioPanels", panels);
    gSavedSettings.setS32("SLPhotoStudioLayout", mLayout);
}

void SLFloaterPhotoStudio::setLayout(S32 count)
{
    const S32 old_layout = mLayout;
    mLayout = (count == 1 || count == 2) ? count : MAX_SLOTS;
    if (mLayoutCombo)
    {
        mLayoutCombo->selectByValue(LLSD(mLayout));
    }

    for (S32 i = 0; i < MAX_SLOTS; ++i)
    {
        SLPhotoStudioSlot* slot = mSlots[i];
        if (!slot)
        {
            continue;
        }
        const bool shown = i < mLayout;
        slot->setVisible(shown);
        if (shown && !mSlotPoppedOut[i] && !slot->hasContent())
        {
            // Coming back into view: built now rather than kept alive hidden.
            slot->setSection(mSlotSections[i], true);
        }
        else if (!shown && i < old_layout)
        {
            // Out of the layout: its section is not built while hidden, and a
            // window it was out in goes too.
            if (LLFloater* pane = LLFloaterReg::findInstance(PANE_FLOATER_NAME, LLSD(i)))
            {
                pane->closeFloater();
            }
            slot->releaseContent();
        }
    }

    applyMinimumSize();
    arrangeSlots();
}

void SLFloaterPhotoStudio::applyMinimumSize()
{
    // The area above the panels: the floater's own chrome and the top bar.
    const S32 chrome_height = mSlotsArea ? getRect().getHeight() - mSlotsArea->getRect().getHeight() : 120;
    const S32 chrome_width = mSlotsArea ? getRect().getWidth() - mSlotsArea->getRect().getWidth() : 8;
    const S32 cols = (mLayout == 1) ? 1 : 2;
    const S32 rows = (mLayout == MAX_SLOTS) ? 2 : 1;
    const S32 min_width = chrome_width + cols * MIN_SLOT_WIDTH + (cols - 1) * SLOT_GAP;
    const S32 min_height = chrome_height + rows * MIN_SLOT_HEIGHT + (rows - 1) * SLOT_GAP;
    setResizeLimits(min_width, min_height);

    const LLRect rect = getRect();
    if (rect.getWidth() < min_width || rect.getHeight() < min_height)
    {
        // Grown from the top left corner, which is where the eye is.
        const S32 width = llmax(rect.getWidth(), min_width);
        const S32 height = llmax(rect.getHeight(), min_height);
        LLRect grown;
        grown.setLeftTopAndSize(rect.mLeft, rect.mTop, width, height);
        setShape(grown);
    }
}

void SLFloaterPhotoStudio::arrangeSlots()
{
    if (!mSlotsArea)
    {
        return;
    }
    const S32 width = mSlotsArea->getRect().getWidth();
    const S32 height = mSlotsArea->getRect().getHeight();
    const S32 half_w = (width - SLOT_GAP) / 2;
    const S32 half_h = (height - SLOT_GAP) / 2;

    std::array<LLRect, MAX_SLOTS> rects;
    switch (mLayout)
    {
    case 1:
        rects[0] = LLRect(0, height, width, 0);
        break;
    case 2:
        rects[0] = LLRect(0, height, half_w, 0);
        rects[1] = LLRect(width - half_w, height, width, 0);
        break;
    default:
        // Reading order: 1 2 over 3 4.
        rects[0] = LLRect(0, height, half_w, height - half_h);
        rects[1] = LLRect(width - half_w, height, width, height - half_h);
        rects[2] = LLRect(0, half_h, half_w, 0);
        rects[3] = LLRect(width - half_w, half_h, width, 0);
        break;
    }
    for (S32 i = 0; i < mLayout && i < MAX_SLOTS; ++i)
    {
        if (mSlots[i] && mSlots[i]->getRect() != rects[i])
        {
            mSlots[i]->setShape(rects[i]);
        }
    }
}

void SLFloaterPhotoStudio::onSlotSectionChanged(S32 index, const std::string& id)
{
    if (index < 0 || index >= MAX_SLOTS)
    {
        return;
    }
    mSlotSections[index] = id;
    if (SLFloaterPhotoStudioPane* pane =
            LLFloaterReg::findTypedInstance<SLFloaterPhotoStudioPane>(PANE_FLOATER_NAME, LLSD(index)))
    {
        pane->refreshTitle();
    }
    // The main panel keeps the section too, so putting the window back shows
    // what was last chosen in it.
    if (mSlotPoppedOut[index] && mSlots[index])
    {
        mSlots[index]->setSection(id);
    }
    saveState();
}

const std::string& SLFloaterPhotoStudio::getSlotSection(S32 index) const
{
    return (index >= 0 && index < MAX_SLOTS) ? mSlotSections[index] : LLStringUtil::null;
}

void SLFloaterPhotoStudio::popOut(S32 index)
{
    if (index < 0 || index >= mLayout || mSlotPoppedOut[index] || !mSlots[index])
    {
        return;
    }
    mSlotPoppedOut[index] = true;
    mSlots[index]->setPoppedOut(true);
    LLFloaterReg::showInstance(PANE_FLOATER_NAME, LLSD(index), true);
    saveState();
}

void SLFloaterPhotoStudio::putBack(S32 index)
{
    if (index < 0 || index >= MAX_SLOTS)
    {
        return;
    }
    if (LLFloater* pane = LLFloaterReg::findInstance(PANE_FLOATER_NAME, LLSD(index)))
    {
        // Its onClose comes back through onPaneClosed with its section.
        pane->closeFloater();
        return;
    }
    onPaneClosed(index, mSlotSections[index]);
}

void SLFloaterPhotoStudio::onPaneClosed(S32 index, const std::string& id)
{
    if (mClosing || index < 0 || index >= MAX_SLOTS)
    {
        return;
    }
    if (!id.empty())
    {
        mSlotSections[index] = id;
    }
    mSlotPoppedOut[index] = false;
    if (mSlots[index])
    {
        mSlots[index]->setSection(mSlotSections[index]);
        mSlots[index]->setPoppedOut(false);
    }
    saveState();
}

// --- Undo ---------------------------------------------------------------------

void SLFloaterPhotoStudio::onGradeSettingChanged(const std::string& name, const LLSD& before, const LLSD& after)
{
    if (mApplyingHistory)
    {
        // Our own write, coming back round. Recording it would append the
        // undo to the stack it was taken from.
        return;
    }
    // A monotonic clock is all the history wants: it compares two of these to
    // decide whether one drag is still in progress.
    mHistory.record(name, before, after, (F32)LLTimer::getElapsedSeconds().value());
}

bool SLFloaterPhotoStudio::applyHistory(bool redo_direction)
{
    const SLGradeHistory::Transaction* stepp = redo_direction ? mHistory.redo() : mHistory.undo();
    if (!stepp)
    {
        return false;
    }

    // Copied, not followed: the pointer is into the history's own stack.
    const SLGradeHistory::Transaction step = *stepp;

    ScopedTrue applying(mApplyingHistory);
    bool effects_changed = false;
    for (const SLGradeHistory::Change& change : step)
    {
        const LLSD& value = redo_direction ? change.mAfter : change.mBefore;
        if (applyEffectChange(change.mName, value))
        {
            effects_changed = true;
            continue;
        }
        if (LLControlVariable* controlp = gSavedSettings.getControl(change.mName))
        {
            controlp->setValue(value);
        }
    }
    if (effects_changed)
    {
        // The effect preset now differs from its file, as any edit does.
        SLFxPresets::instance().markDirty();
    }
    // Deliberately no attempt to restore which Look was active: undo restores
    // values, and the Look stays dirty, as it would if the old numbers had
    // been typed back in.
    return true;
}

void SLFloaterPhotoStudio::refreshHistoryButtons()
{
    const S32 state = (mHistory.canUndo() ? 1 : 0) | (mHistory.canRedo() ? 2 : 0);
    if (state == mHistoryButtonState)
    {
        return;
    }
    mHistoryButtonState = state;
    if (mUndoButton)
    {
        mUndoButton->setEnabled((state & 1) != 0);
    }
    if (mRedoButton)
    {
        mRedoButton->setEnabled((state & 2) != 0);
    }
}

void SLFloaterPhotoStudio::openHistory()
{
    LLFloaterReg::showInstance(HISTORY_FLOATER_NAME, LLSD(), true);
}

std::vector<SLFloaterPhotoStudio::HistoryRow> SLFloaterPhotoStudio::getHistoryRows()
{
    std::vector<HistoryRow> rows;
    if (mHistory.depth() == 0)
    {
        return rows;
    }

    // A first row that is no step at all: where the history starts. Without
    // it no row could ask for nothing to be in force.
    rows.push_back({ getString("history_start"), std::string() });
    for (size_t index = 0; index < mHistory.depth(); ++index)
    {
        const SLGradeHistory::Transaction& changes = mHistory.at(index);
        HistoryRow row;
        row.mWhat = mHistory.labelOf(index);
        if (row.mWhat.empty())
        {
            if (changes.size() == 1)
            {
                row.mWhat = captionFor(changes.front().mName);
            }
            else
            {
                LLStringUtil::format_map_t args;
                args["[COUNT]"] = llformat("%d", (S32)changes.size());
                row.mWhat = getString("history_settings", args);
            }
        }

        // Where, when every change in the step is in one section: that is
        // what tells five Strength steps apart.
        std::string common;
        bool one_section = !changes.empty();
        for (const SLGradeHistory::Change& change : changes)
        {
            const std::string where = sectionTitleFor(change.mName);
            if (where.empty() || (!common.empty() && where != common))
            {
                one_section = false;
                break;
            }
            common = where;
        }
        if (one_section)
        {
            row.mWhere = common;
        }
        rows.push_back(std::move(row));
    }
    return rows;
}

void SLFloaterPhotoStudio::goToHistory(size_t cursor)
{
    // A step at a time through applyHistory, so every step is written back
    // exactly the way Ctrl+Z and Ctrl+Y write it.
    size_t guard = mHistory.depth() + 1;
    while (mHistory.cursor() > cursor && guard-- > 0)
    {
        if (!applyHistory(false))
        {
            break;
        }
    }
    while (mHistory.cursor() < cursor && guard-- > 0)
    {
        if (!applyHistory(true))
        {
            break;
        }
    }
}

