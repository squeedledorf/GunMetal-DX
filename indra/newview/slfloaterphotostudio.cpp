SLFloaterPhotoStudioHistory::SLFloaterPhotoStudioHistory(const LLSD& key)
:   LLFloater(key)
{
}

bool SLFloaterPhotoStudioHistory::postBuild()
{
    mList = getChild<LLScrollListCtrl>("history_list");
    mEmpty = getChildView("history_empty");
    mList->setDoubleClickCallback([this]() { goToSelected(); });
    getChild<LLUICtrl>("history_go")->setCommitCallback([this](LLUICtrl*, const LLSD&) { goToSelected(); });
    return LLFloater::postBuild();
}

void SLFloaterPhotoStudioHistory::draw()
{
    // Follows the stack while it is up: Ctrl+Z, a drag in a panel, a Look
    // applied from the bar.
    SLFloaterPhotoStudio* studio = SLFloaterPhotoStudio::findInstance();
    if (studio && (studio->getHistory().revision() != mRevision || studio->getHistory().cursor() != mCursor))
    {
        fill();
    }
    LLFloater::draw();
}

void SLFloaterPhotoStudioHistory::fill()
{
    SLFloaterPhotoStudio* studio = SLFloaterPhotoStudio::findInstance();
    if (!studio || !mList)
    {
        return;
    }
    const SLGradeHistory& history = studio->getHistory();
    mRevision = history.revision();
    mCursor = history.cursor();

    mList->deleteAllItems();
    const std::vector<SLFloaterPhotoStudio::HistoryRow> rows = studio->getHistoryRows();
    for (size_t i = 0; i < rows.size(); ++i)
    {
        LLSD row;
        row["columns"][0]["column"] = "what";
        row["columns"][0]["value"] = rows[i].mWhat;
        row["columns"][1]["column"] = "where";
        row["columns"][1]["value"] = rows[i].mWhere;
        row["columns"][2]["column"] = "now";
        row["columns"][2]["value"] = (i == mCursor) ? getString("current_marker") : std::string();
        // Steps past the present are undone: grey, as a redo tail reads.
        if (i > mCursor)
        {
            row["columns"][0]["color"] = LLColor4::grey.getValue();
            row["columns"][1]["color"] = LLColor4::grey.getValue();
        }
        mList->addElement(row);
    }
    if (!rows.empty())
    {
        mList->selectNthItem((S32)llmin(mCursor, rows.size() - 1));
        mList->scrollToShowSelected();
    }
    if (mEmpty)
    {
        mEmpty->setVisible(rows.empty());
    }
}

void SLFloaterPhotoStudioHistory::goToSelected()
{
    SLFloaterPhotoStudio* studio = SLFloaterPhotoStudio::findInstance();
    if (!studio || !mList)
    {
        return;
    }
    const S32 index = mList->getFirstSelectedIndex();
    if (index >= 0)
    {
        // Row 0 is the start of the history, row n step n: the row is the
        // number of steps that should be in force.
        studio->goToHistory((size_t)index);
    }
}
