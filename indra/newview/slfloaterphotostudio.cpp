void SLFloaterPhotoStudio::pickWhiteBalance()
{
    SLToolScenePicker* picker = SLToolScenePicker::getInstance();

    // A handle, not `this`: the tool stays armed until something is clicked,
    // and the sample only arrives a frame after the click, so the floater can
    // be closed in between.
    LLHandle<LLFloater> handle = getHandle();
    picker->setPickCallback([handle](const LLColor3& sample)
    {
        if (SLFloaterPhotoStudio* self = dynamic_cast<SLFloaterPhotoStudio*>(handle.get()))
        {
            self->onWhiteBalancePicked(sample);
        }
    });
    LLToolMgr::getInstance()->setTransientTool(picker);
}

void SLFloaterPhotoStudio::onWhiteBalancePicked(const LLColor3& sample)
{
    // The ratios of three near-zero numbers are noise, and a sample in shadow
    // is exactly where a missed click lands. Refuse rather than swing the
    // sliders to an answer read out of rounding error.
    constexpr F32 MIN_LUMA = 1e-3f;
    const F32 luma = sample.mV[0] * 0.2126f + sample.mV[1] * 0.7152f + sample.mV[2] * 0.0722f;
    if (luma < MIN_LUMA)
    {
        LLNotificationsUtil::add("PhotoStudioWhiteBalanceTooDark");
        return;
    }

    const SLWhiteBalanceSolver::Result solved = SLWhiteBalanceSolver::solveForColor(sample);

    // Past this the sliders cannot express what was asked for -- a strongly
    // coloured surface, not a neutral one lit by coloured light.
    constexpr F32 MAX_RESIDUAL = 0.02f;
    if (solved.mResidual > MAX_RESIDUAL)
    {
        LLNotificationsUtil::add("PhotoStudioWhiteBalanceUnreachable");
        return;
    }

    // One pick is one thing the user did, though it moves two sliders.
    ScopedHistoryGroup group(mHistory, getString("history_white_balance"));
    gSavedSettings.setF32("RenderColorGradeWhiteBalanceCCT", solved.mCCTOffset);
    gSavedSettings.setF32("RenderColorGradeWhiteBalanceDuv", solved.mDuv);
}

// --- Day cycle ------------------------------------------------------------------

std::shared_ptr<LLSettingsDay> SLFloaterPhotoStudio::getScrubbableDay() const
{
    // The order the viewer itself resolves environments in. ENV_LOCAL leads
    // because a day the user applied is the one they would expect to scrub;
    // while frozen it holds a fixed sky and no day, so the search falls
    // through to whatever the parcel or region is running.
    static const LLEnvironment::EnvSelection_t sources[] = {
        LLEnvironment::ENV_LOCAL, LLEnvironment::ENV_PUSH,
        LLEnvironment::ENV_PARCEL, LLEnvironment::ENV_REGION };

    for (LLEnvironment::EnvSelection_t env : sources)
    {
        if (LLSettingsDay::ptr_t day = LLEnvironment::instance().getEnvironmentDay(env))
        {
            return day;
        }
    }
    return {};
}

bool SLFloaterPhotoStudio::isSkyFrozen() const
{
    return (bool)LLEnvironment::instance().getEnvironmentFixedSky(LLEnvironment::ENV_LOCAL);
}

const SLFloaterPhotoStudio::DayCycleState& SLFloaterPhotoStudio::getDayCycleState()
{
    const U32 frame = LLFrameTimer::getFrameCount();
    if (mDayStateValid && mDayStateFrame == frame)
    {
        return mDayState;
    }
    mDayStateValid = true;
    mDayStateFrame = frame;

    mDayState.mCanChange = RlvActions::canChangeEnvironment();
    mDayState.mFrozen = isSkyFrozen();
    mDayState.mHasDay = (bool)getScrubbableDay();

    // While the sky is running, the position tracks the live one, so ticking
    // Freeze holds the moment being looked at rather than jumping.
    if (!mDayState.mFrozen)
    {
        const F32 live = LLEnvironment::instance().getProgress();
        if (live >= 0.f)
        {
            mDayState.mPosition = live;
        }
        // A sky frozen by something else, then cleared by it, leaves us
        // holding a restore point for an environment that is already back.
        mDayFreezeIsOurs = false;
    }

    // Polled alongside because the World menu can pause clouds too.
    mDayState.mCloudsPaused = LLEnvironment::instance().isCloudScrollPaused();

    // Presets cost a search, so only look when the row is usable.
    if (mDayState.mCanChange && mDayState.mHasDay)
    {
        refreshDayLandmarks();
    }
    mDayState.mPresent = { { mDayLandmarks.has_sunrise, mDayLandmarks.has_noon,
                             mDayLandmarks.has_sunset, mDayLandmarks.has_midnight } };
    return mDayState;
}

void SLFloaterPhotoStudio::applyDayPosition(F32 position)
{
    LLSettingsDay::ptr_t day = getScrubbableDay();
    if (!day)
    {
        return;
    }

    mDayState.mPosition = llclamp(position, 0.f, 1.f);

    // A day cycle carries up to four sky tracks and which one you see depends
    // on how high you are, so sample the one the agent is in. Track 0 is
    // water, and it is sampled too: a frozen sky over a moving sea is not
    // frozen.
    const S32 track = LLEnvironment::instance().calculateSkyTrackForAltitude(
        gAgent.getPositionAgent().mV[VZ]);

    LLSettingsSky::ptr_t sky = LLSettingsVOSky::buildDefaultSky();
    LLSettingsWater::ptr_t water = LLSettingsVOWater::buildDefaultWater();

    std::make_shared<LLTrackBlenderLoopingManual>(sky, day, track)->setPosition(mDayState.mPosition);
    std::make_shared<LLTrackBlenderLoopingManual>(water, day, (S32)LLSettingsDay::TRACK_WATER)
        ->setPosition(mDayState.mPosition);

    LLEnvironment::instance().setEnvironment(LLEnvironment::ENV_LOCAL, sky, water);
    LLEnvironment::instance().setSelectedEnvironment(LLEnvironment::ENV_LOCAL, LLEnvironment::TRANSITION_INSTANT);
    LLEnvironment::instance().updateEnvironment(LLEnvironment::TRANSITION_INSTANT);
}

void SLFloaterPhotoStudio::freezeSkyAt(F32 position)
{
    if (!mDayFreezeIsOurs)
    {
        // Whatever is here now is about to be covered up, and unticking
        // Freeze has to give it back -- a Personal Lighting sky included.
        LLEnvironment& env = LLEnvironment::instance();
        mPreFreezeDay = env.getEnvironmentDay(LLEnvironment::ENV_LOCAL);
        if (mPreFreezeDay)
        {
            mPreFreezeDayLength = env.getEnvironmentDayLength(LLEnvironment::ENV_LOCAL).value();
            mPreFreezeDayOffset = env.getEnvironmentDayOffset(LLEnvironment::ENV_LOCAL).value();
        }
        const LLEnvironment::fixedEnvironment_t fixed = env.getEnvironmentFixed(LLEnvironment::ENV_LOCAL);
        mPreFreezeSky = fixed.first;
        mPreFreezeWater = fixed.second;
        mDayFreezeIsOurs = true;
    }

    applyDayPosition(position);
    mDayStateValid = false;
}

void SLFloaterPhotoStudio::thawSky()
{
    LLEnvironment& env = LLEnvironment::instance();

    if (mDayFreezeIsOurs && mPreFreezeDay)
    {
        env.setEnvironment(LLEnvironment::ENV_LOCAL, mPreFreezeDay,
                           LLSettingsDay::Seconds(mPreFreezeDayLength),
                           LLSettingsDay::Seconds(mPreFreezeDayOffset));
    }
    else if (mDayFreezeIsOurs && (mPreFreezeSky || mPreFreezeWater))
    {
        env.setEnvironment(LLEnvironment::ENV_LOCAL, mPreFreezeSky, mPreFreezeWater);
    }
    else
    {
        // Nothing to give back, so fall through to the parcel or region.
        env.clearEnvironment(LLEnvironment::ENV_LOCAL);
    }

    env.setSelectedEnvironment(LLEnvironment::ENV_LOCAL, LLEnvironment::TRANSITION_INSTANT);
    env.updateEnvironment(LLEnvironment::TRANSITION_INSTANT);

    mPreFreezeDay.reset();
    mPreFreezeSky.reset();
    mPreFreezeWater.reset();
    mDayFreezeIsOurs = false;
    mDayStateValid = false;
}

void SLFloaterPhotoStudio::refreshDayLandmarks()
{
    LLSettingsDay::ptr_t day = getScrubbableDay();
    if (day == mLandmarkDay)
    {
        return;
    }

    mLandmarkDay = day;
    mDayLandmarks = SLDayCycleLandmarks::Landmarks();
    if (!day)
    {
        return;
    }

    // One scratch sky, re-blended at each sample. The sun direction's Z is
    // its height above the horizon, the only thing that says where noon is
    // in a cycle whose keyframes could be anywhere.
    const S32 track = LLEnvironment::instance().calculateSkyTrackForAltitude(
        gAgent.getPositionAgent().mV[VZ]);
    LLSettingsSky::ptr_t scratch = LLSettingsVOSky::buildDefaultSky();
    auto blender = std::make_shared<LLTrackBlenderLoopingManual>(scratch, day, track);

    mDayLandmarks = SLDayCycleLandmarks::find(
        [&blender, &scratch](F32 position)
        {
            blender->setPosition(position);
            return scratch->getSunDirection().mV[VZ];
        });
}

void SLFloaterPhotoStudio::setDayFrozen(bool frozen)
{
    if (frozen)
    {
        freezeSkyAt(getDayCycleState().mPosition);
    }
    else
    {
        thawSky();
    }
}

void SLFloaterPhotoStudio::scrubDay(F32 position)
{
    // Through freezeSkyAt, not applyDayPosition: "frozen" can also mean a
    // fixed sky somebody else installed, which the first scrub covers up, so
    // it is the moment to remember it. Once the freeze is ours the capture is
    // skipped and a drag costs nothing extra.
    freezeSkyAt(position);
}

void SLFloaterPhotoStudio::goToDayPreset(const std::string& which)
{
    refreshDayLandmarks();
    const SLDayCycleLandmarks::Landmarks& marks = mDayLandmarks;

    F32 position = 0.f;
    if (which == "sunrise" && marks.has_sunrise)        { position = marks.sunrise; }
    else if (which == "noon" && marks.has_noon)         { position = marks.noon; }
    else if (which == "sunset" && marks.has_sunset)     { position = marks.sunset; }
    else if (which == "midnight" && marks.has_midnight) { position = marks.midnight; }
    else                                                { return; }

    // A preset moves the slider and freezes there; it does not install a
    // canned sky, so the region's own idea of noon is what you get.
    freezeSkyAt(position);
}

void SLFloaterPhotoStudio::restoreEnvironment()
{
    // Unconditional, unlike unticking Freeze: the way back to the parcel or
    // region whatever we happen to be holding.
    mDayFreezeIsOurs = false;
    mPreFreezeDay.reset();
    mPreFreezeSky.reset();
    mPreFreezeWater.reset();
    thawSky();
}

// --- Find and the catalog ---------------------------------------------------------

void SLFloaterPhotoStudio::buildCatalog()
{
    if (mCatalogBuilt)
    {
        return;
    }
    mCatalogBuilt = true;

    // Every page, built once and thrown away: the directory each builds is
    // what the history names steps by and Find searches, whatever the panels
    // happen to be showing.
    for (const std::string& page : SLPhotoStudioSections::pages())
    {
        const SLPhotoStudioSectionDef* def = SLPhotoStudioSections::page(page);
        if (!def)
        {
            continue;
        }
        SLPanelPhotoStudioSection* panel = new SLPanelPhotoStudioSection(this, *def);
        if (panel->build())
        {
            const SLPhotoStudioDirectory& dir = panel->getDirectory();
            const size_t base = mCatalogSections.size();
            for (const SLPhotoStudioDirectory::Section& section : dir.sections())
            {
                mCatalogSections.push_back({ page, section.mName, section.mTitle });
            }
            for (const SLPhotoStudioDirectory::Setting& setting : dir.settings())
            {
                if (!catalogSetting(setting.mKey))
                {
                    mCatalogSettings.push_back({ setting.mKey, setting.mCaption, base + setting.mSection });
                }
            }
        }
        delete panel;
    }
}

const SLFloaterPhotoStudio::CatalogSetting* SLFloaterPhotoStudio::catalogSetting(const std::string& key)
{
    for (const CatalogSetting& setting : mCatalogSettings)
    {
        if (setting.mKey == key)
        {
            return &setting;
        }
    }
    return nullptr;
}

