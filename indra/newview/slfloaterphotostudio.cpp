/// What a fresh Photo Studio shows: four panels, the two grading pages, the
/// sky and the scopes.
const std::array<const char*, SLFloaterPhotoStudio::MAX_SLOTS> DEFAULT_SECTIONS = { { "look", "lens", "sky", "scopes" } };

/// Count of grading sections switched off for comparison.
S32 bypassedSections(U32 mask)
{
    static constexpr U32 section_bits[] = {
        LLPipeline::GRADE_BYPASS_BASIC,
        LLPipeline::GRADE_BYPASS_PRIMARIES,
        LLPipeline::GRADE_BYPASS_SPLIT,
        LLPipeline::GRADE_BYPASS_LUT,
        LLPipeline::GRADE_BYPASS_CURVE,
    };
    S32 count = 0;
    for (U32 bit : section_bits)
    {
        if (mask & bit)
        {
            ++count;
        }
    }
    return count;
}

/// How well @a hay matches @a needle (both lower case): 0 exact, 1 prefix,
/// 2 a word's prefix, 3 anywhere; -1 not at all.
S32 matchScore(const std::string& hay, const std::string& needle)
{
    if (needle.empty())
    {
        return -1;
    }
    if (hay == needle)
    {
        return 0;
    }
    const size_t at = hay.find(needle);
    if (at == std::string::npos)
    {
        return -1;
    }
    if (at == 0)
    {
        return 1;
    }
    if (!isalnum((unsigned char)hay[at - 1]))
    {
        return 2;
    }
    return 3;
}
