SLFloaterPhotoStudio::SLFloaterPhotoStudio(const LLSD& key)
:   LLFloater(key)
{
    mCommitCallbackRegistrar.add("PhotoStudio.Undo", [this](LLUICtrl*, const LLSD&) { applyHistory(false); });
    mCommitCallbackRegistrar.add("PhotoStudio.Redo", [this](LLUICtrl*, const LLSD&) { applyHistory(true); });
    mCommitCallbackRegistrar.add("PhotoStudio.History", [this](LLUICtrl*, const LLSD&) { openHistory(); });
    mCommitCallbackRegistrar.add("PhotoStudio.Find", [this](LLUICtrl*, const LLSD&) { onFind(); });
    mCommitCallbackRegistrar.add("PhotoStudio.Layout", [this](LLUICtrl* ctrl, const LLSD&)
    {
        setLayout(ctrl ? ctrl->getValue().asInteger() : MAX_SLOTS);
        saveState();
    });
    mCommitCallbackRegistrar.add("PhotoStudio.LookSelected", [this](LLUICtrl*, const LLSD&) { onLookSelected(); });
    mCommitCallbackRegistrar.add("PhotoStudio.LookSave", [this](LLUICtrl*, const LLSD&) { onClickLookSave(); });
    mCommitCallbackRegistrar.add("PhotoStudio.LookSaveAs", [this](LLUICtrl*, const LLSD&) { onClickLookSaveAs(); });
    mCommitCallbackRegistrar.add("PhotoStudio.LookDelete", [this](LLUICtrl*, const LLSD&) { onClickLookDelete(); });
    mCommitCallbackRegistrar.add("PhotoStudio.LookRevert", [this](LLUICtrl*, const LLSD&) { onClickLookRevert(); });

    for (S32 i = 0; i < MAX_SLOTS; ++i)
    {
        mSlotSections[i] = DEFAULT_SECTIONS[i];
    }
}

SLFloaterPhotoStudio::~SLFloaterPhotoStudio()
{
    // An armed white balance picker outliving the floater would leave the
    // user holding an eyedropper cursor that has nothing left to tell. Put
    // the previous tool back instead.
    if (LLToolMgr::instanceExists() &&
        LLToolMgr::getInstance()->getCurrentTool() == SLToolScenePicker::getInstance())
    {
        LLToolMgr::getInstance()->clearTransientTool();
    }

    // The bypass mask lives in the pipeline and the switches that drive it
    // live in the panels, so closing with one off would leave a section
    // suppressed with nothing on screen to say so. The comparison ends when
    // the tool does.
    LLPipeline::sGradeBypassMask = 0;

    // Same rule for the reference still, with a second reason: it is a
    // full-resolution target, so leaving one behind holds real memory for a
    // comparison nobody can see or turn off any more.
    gSavedSettings.setS32("RenderReferenceWipeMode", 0);
    gPipeline.clearReferenceStill();
}

