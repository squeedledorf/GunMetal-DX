SLFloaterPhotoStudioPane::SLFloaterPhotoStudioPane(const LLSD& key)
:   LLFloater(key),
    mIndex(llclamp((S32)key.asInteger(), 0, SLFloaterPhotoStudio::MAX_SLOTS - 1))
{
}

bool SLFloaterPhotoStudioPane::postBuild()
{
    SLFloaterPhotoStudio* studio = SLFloaterPhotoStudio::findInstance();
    LLPanel* body = getChild<LLPanel>("pane_body");

    mSlot = new SLPhotoStudioSlot(studio, mIndex, true);
    mSlot->build();
    // setShape, so the panel lays its children out from its XUI size.
    mSlot->setFollowsAll();
    body->addChild(mSlot);
    mSlot->setShape(body->getLocalRect());
    mSlot->setSection(studio ? studio->getSlotSection(mIndex) : std::string("look"), true);

    refreshTitle();
    return LLFloater::postBuild();
}

void SLFloaterPhotoStudioPane::refreshTitle()
{
    if (!mSlot)
    {
        return;
    }
    LLStringUtil::format_map_t args;
    args["[SECTION]"] = mSlot->getSectionLabel();
    setTitle(getString("title_format", args));
}

void SLFloaterPhotoStudioPane::onClose(bool app_quitting)
{
    // Closing the window puts the panel back -- unless Photo Studio itself is
    // closing (it closes these and remembers them as out) or the viewer is.
    SLFloaterPhotoStudio* studio = SLFloaterPhotoStudio::findInstance();
    if (studio && !studio->isClosing() && !app_quitting && mSlot)
    {
        studio->onPaneClosed(mIndex, mSlot->getSectionId());
    }
    LLFloater::onClose(app_quitting);
}

bool SLFloaterPhotoStudioPane::handleKeyHere(KEY key, MASK mask)
{
    if (SLFloaterPhotoStudio* studio = SLFloaterPhotoStudio::findInstance())
    {
        if (studio->handleStudioKey(key, mask))
        {
            return true;
        }
    }
    return LLFloater::handleKeyHere(key, mask);
}

