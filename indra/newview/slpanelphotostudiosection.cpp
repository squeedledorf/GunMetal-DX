SLPanelPhotoStudioSection::SLPanelPhotoStudioSection(SLFloaterPhotoStudio* studio, const SLPhotoStudioSectionDef& def)
:   LLPanel(),
    mDef(def)
{
    if (studio)
    {
        mStudio = studio->getHandle();
    }

    // Registered before the XUI is built, which resolves these names as it
    // parses. Every name the page files use is here.
    mCommitCallbackRegistrar.add("PhotoStudio.ResetControlDefault",
        [this](LLUICtrl*, const LLSD& param) { onResetControlDefault(param); });
    mCommitCallbackRegistrar.add("PhotoStudio.ResetSection",
        [this](LLUICtrl*, const LLSD& param) { onResetSection(param); });
    mCommitCallbackRegistrar.add("PhotoStudio.ToggleSection",
        [this](LLUICtrl* ctrl, const LLSD& param) { onToggleSection(ctrl, param); });
    mCommitCallbackRegistrar.add("PhotoStudio.ReferenceGrab", [this](LLUICtrl*, const LLSD&)
    {
        // The grab is serviced on the next frame's blit, so what gets frozen
        // is what the user is looking at as they click. Switching the wipe on
        // is the feedback that the grab happened.
        gPipeline.requestReferenceStill();
        if (gSavedSettings.getS32("RenderReferenceWipeMode") == 0)
        {
            gSavedSettings.setS32("RenderReferenceWipeMode", 1);
        }
        refreshReferenceRow();
    });
    mCommitCallbackRegistrar.add("PhotoStudio.ReferenceClear", [this](LLUICtrl*, const LLSD&)
    {
        gSavedSettings.setS32("RenderReferenceWipeMode", 0);
        gPipeline.clearReferenceStill();
        refreshReferenceRow();
    });
    mCommitCallbackRegistrar.add("PhotoStudio.ToggleDayFreeze",
        [this](LLUICtrl* ctrl, const LLSD&) { onToggleDayFreeze(ctrl); });
    mCommitCallbackRegistrar.add("PhotoStudio.CommitDayTime",
        [this](LLUICtrl* ctrl, const LLSD&) { onCommitDayTime(ctrl); });
    mCommitCallbackRegistrar.add("PhotoStudio.DayPreset",
        [this](LLUICtrl*, const LLSD& param) { onClickDayPreset(param); });
    mCommitCallbackRegistrar.add("PhotoStudio.ToggleCloudScroll",
        [this](LLUICtrl* ctrl, const LLSD&) { onToggleCloudScroll(ctrl); });
    mCommitCallbackRegistrar.add("PhotoStudio.RestoreEnvironment", [this](LLUICtrl*, const LLSD&)
    {
        if (SLFloaterPhotoStudio* floater = this->studio())
        {
            floater->restoreEnvironment();
        }
        mDayCycleRowState = -1;
    });
    mCommitCallbackRegistrar.add("PhotoStudio.CommitVec3",
        [this](LLUICtrl* ctrl, const LLSD&) { onCommitVec3(ctrl); });
    mCommitCallbackRegistrar.add("PhotoStudio.CommitToneCurve",
        [this](LLUICtrl*, const LLSD&) { onCommitToneCurve(); });
    mCommitCallbackRegistrar.add("PhotoStudio.RefreshToneCurve",
        [this](LLUICtrl*, const LLSD&) { refreshToneCurve(); });
    mCommitCallbackRegistrar.add("PhotoStudio.ResetToneCurveChannel",
        [this](LLUICtrl*, const LLSD&) { onClickResetToneCurveChannel(); });
    mCommitCallbackRegistrar.add("PhotoStudio.ToneCurvePreset",
        [this](LLUICtrl*, const LLSD& param) { onToneCurvePreset(param); });
    mCommitCallbackRegistrar.add("PhotoStudio.CommitSplitToneGraph",
        [this](LLUICtrl*, const LLSD&) { onCommitSplitToneGraph(); });
    mCommitCallbackRegistrar.add("PhotoStudio.PickWhiteBalance", [this](LLUICtrl*, const LLSD&)
    {
        if (SLFloaterPhotoStudio* floater = this->studio())
        {
            floater->pickWhiteBalance();
        }
    });
    mCommitCallbackRegistrar.add("PhotoStudio.OpenLUTFolder", [](LLUICtrl*, const LLSD&)
    {
        // The user's folder, not the bundled one: it is the half of the pair
        // that is theirs to put files in, and the one the renderer prefers
        // when a name exists in both. LLFile::mkdir is quiet about a folder
        // that already exists.
        const std::string dir = gDirUtilp->getExpandedFilename(LL_PATH_USER_SETTINGS, "colorlut");
        LLFile::mkdir(dir);
        gDirUtilp->openDir(dir);
    });
    // The lens dirt plate is regenerated whenever one of its parameters
    // changes, which at full resolution is too dear for every frame of a drag:
    // the renderer holds off while this is raised and rebuilds on release.
    mCommitCallbackRegistrar.add("PhotoStudio.LensDirtSliderDown",
        [](LLUICtrl*, const LLSD&) { gPipeline.mLensDirtSliderHeld = true; });
    mCommitCallbackRegistrar.add("PhotoStudio.LensDirtSliderUp",
        [](LLUICtrl*, const LLSD&) { gPipeline.mLensDirtSliderHeld = false; });
    mCommitCallbackRegistrar.add("PhotoStudio.ToggleHUDInfo",
        [this](LLUICtrl*, const LLSD& param) { onToggleHUDInfo(param); });
}

