void SLPanelPhotoStudioSection::setupToneCurve()
{
    mToneCurve = findChild<SLCurveEditorCtrl>("tone_curve_graph");
    if (!mToneCurve)
    {
        return;
    }
    mToneCurveChannel = findChild<LLComboBox>("tone_curve_channel");
    if (mToneCurveChannel)
    {
        // Start on Master. Without an explicit selection an unselected combo
        // reads back as 0, which would silently mean "red only".
        mToneCurveChannel->selectByValue(LLSD(-1));
    }

    for (S32 c = 0; c < SLToneCurveSet::CH_COUNT; ++c)
    {
        const char* key = SLToneCurveSet::settingName(static_cast<SLToneCurveSet::EChannel>(c));
        if (LLControlVariable* controlp = gSavedSettings.getControl(key))
        {
            mToneCurveConnections.emplace_back(controlp->getSignal()->connect(
                [this](LLControlVariable*, const LLSD&, const LLSD&) { refreshToneCurve(); }));
        }
    }

    // The graph names the settings it edits in XUI so the section's Reset All
    // can find them; a typo there fails silently, so say so once.
    for (const std::string& name : mToneCurve->getEditedSettingNames())
    {
        if (!gSavedSettings.getControl(name))
        {
            LL_WARNS() << "tone_curve_graph names an unknown setting: " << name << LL_ENDL;
        }
    }

    refreshToneCurve();
}

void SLPanelPhotoStudioSection::refreshToneCurve()
{
    if (!mToneCurve || mToneCurveUpdating)
    {
        return;
    }

    const SLToneCurveSet curves = loadToneCurveSet();
    const SLToneCurveSet::EChannel channel = SLToneCurveSet::channelFromCombo(getToneCurveChannel());
    // A copy: the lambdas below outlive this call.
    const SLCurveModel selected = curves.curve(channel);

    // The selected curve alone is drawn solid. Its points are the handles, so
    // what is seen is exactly what a drag edits.
    mToneCurve->setCurve([selected](F32 x) { return selected.evaluate(x); });

    mToneCurve->clearGhostCurves();
    if (channel != SLToneCurveSet::CH_MASTER &&
        !SLToneCurveSet::isIdentityCurve(curves.curve(SLToneCurveSet::CH_MASTER)))
    {
        mToneCurve->addGhostCurve([curves, channel](F32 x) { return curves.evaluate(channel, x); }, COMPOSITE_TINT);
    }
    for (S32 i = 0; i < 3; ++i)
    {
        const SLToneCurveSet::EChannel other = static_cast<SLToneCurveSet::EChannel>(SLToneCurveSet::CH_RED + i);
        if (other == channel || SLToneCurveSet::isIdentityCurve(curves.curve(other)))
        {
            continue;
        }
        const SLCurveModel ghost = curves.curve(other);
        mToneCurve->addGhostCurve([ghost](F32 x) { return ghost.evaluate(x); }, CHANNEL_TINT[i]);
    }

    // One handle per point, in point order: getActiveHandle() is then the
    // point index, which is the whole contract onCommitToneCurve relies on.
    std::vector<SLCurveEditorCtrl::Handle> handles;
    const std::vector<SLCurveModel::Point>& points = selected.getPoints();
    for (size_t i = 0; i < points.size(); ++i)
    {
        SLCurveEditorCtrl::Handle h;
        const bool endpoint = (i == 0 || i + 1 == points.size());
        h.mX = points[i].mX;
        h.mY = points[i].mY;
        // The model pins the ends too; the lock stops the pointer fighting it.
        h.mLockX = endpoint;
        h.mColor = (channel == SLToneCurveSet::CH_MASTER)
                       ? LLColor4::white
                       : CHANNEL_SOLID[channel - SLToneCurveSet::CH_RED];
        handles.push_back(h);
    }
    mToneCurve->setHandles(std::move(handles));
}

void SLPanelPhotoStudioSection::onCommitToneCurve()
{
    if (!mToneCurve)
    {
        return;
    }
    const SLCurveEditorCtrl::EAction action = mToneCurve->getAction();
    if (action == SLCurveEditorCtrl::ACTION_NONE)
    {
        return;
    }

    const SLToneCurveSet::EChannel channel = SLToneCurveSet::channelFromCombo(getToneCurveChannel());
    LLControlVariable* controlp = gSavedSettings.getControl(SLToneCurveSet::settingName(channel));
    if (!controlp)
    {
        return;
    }

    SLToneCurveSet curves = loadToneCurveSet();
    SLCurveModel& curve = curves.curve(channel);

    bool changed = false;
    switch (action)
    {
        case SLCurveEditorCtrl::ACTION_DRAG:
        {
            const S32 index = mToneCurve->getActiveHandle();
            if (index < 0 || index >= curve.getPointCount() || index >= (S32)mToneCurve->getHandles().size())
            {
                return;
            }
            // By value: the refresh below replaces the handle list.
            const SLCurveEditorCtrl::Handle handle = mToneCurve->getHandles()[index];
            // Clamps into the neighbours' gap; the ends stay pinned.
            curve.movePoint(index, handle.mX, handle.mY);
            changed = true;
            break;
        }
        case SLCurveEditorCtrl::ACTION_ADD:
            // Past the cap the click is simply ignored; the tooltip states the
            // limit.
            changed = curve.addPoint(mToneCurve->getActionX(), mToneCurve->getActionY()) >= 0;
            break;
        case SLCurveEditorCtrl::ACTION_REMOVE:
        {
            const S32 index = mToneCurve->getActiveHandle();
            if (index < 0 || index >= curve.getPointCount())
            {
                return;
            }
            // False for an endpoint or a two-point curve.
            changed = curve.removePoint(index);
            break;
        }
        default:
            break;
    }

    if (!changed)
    {
        // Put the handle back where the model kept the point.
        refreshToneCurve();
        return;
    }

    // One setting per commit: that is what lets the history coalesce a drag
    // into a single undo step. Writing the setting re-enters through its
    // signal; let the write land, then rebuild the handles once from the
    // values that actually stuck.
    {
        ScopedTrue updating(mToneCurveUpdating);
        controlp->set(SLToneCurveSet::pointsToLLSD(curve.getPoints()));
    }
    refreshToneCurve();
}

