bool SLPanelPhotoStudioSection::build()
{
    if (mDef.isScopes() || mDef.isEffects())
    {
        return false;
    }
    return buildFromFile(mDef.fileName());
}

bool SLPanelPhotoStudioSection::postBuild()
{
    // Every section and setting, before anything else looks for one: from
    // here on this panel finds its own widgets through the directory, so two
    // panels showing the same page never reach into each other.
    mDirectory.build({ this });

    populateLUTCombo(findChild<LLComboBox>("colorlut_combo"));

    // Khronos Neutral (0), ACES (1) and GT (5) take no parameters, so their
    // selection leaves every one of these rows greyed.
    static const std::pair<const char*, S32> tonemapper_rows[] = {
        { "tone_aces_white", 2 },
        { "tone_reinhard_white", 3 },
        { "tone_filmic_white", 4 },
        { "tone_agx_contrast", 6 },
        { "tone_agx_white", 6 },
    };
    for (const auto& row : tonemapper_rows)
    {
        if (LLUICtrl* ctrl = findChild<LLUICtrl>(row.first))
        {
            mTonemapperRows.push_back({ row.second, ctrl, findChild<LLUICtrl>(std::string(row.first) + "_rst") });
        }
    }
    if (!mTonemapperRows.empty())
    {
        mTonemapConnection = gSavedSettings.getControl("SlipstreamRenderTonemapType")->getSignal()->connect(
            [this](LLControlVariable*, const LLSD&, const LLSD&) { updateTonemapperRows(); });
    }
    // HDR is switched from Preferences ("HDR and Emissive"), possibly with
    // this panel up: Bloom or Glow, and the tonemapper rows (none in vintage
    // mode), follow it.
    mHDRConnection = gSavedSettings.getControl("RenderHDREnabled")->getSignal()->connect(
        [this](LLControlVariable*, const LLSD&, const LLSD&) { refreshBloomSections(); updateTonemapperRows(); });
    updateTonemapperRows();

    mReferenceClear = findChild<LLUICtrl>("reference_clear");
    mReferenceMode = findChild<LLUICtrl>("reference_mode");
    mReferencePosition = findChild<LLUICtrl>("reference_position");

    mCamShowFOV = findChild<LLUICtrl>("cam_show_fov");
    mCamShowPosition = findChild<LLUICtrl>("cam_show_position");

    mDayFreeze = findChild<LLUICtrl>("day_freeze");
    mDayTime = findChild<LLUICtrl>("day_time");
    mCloudScroll = findChild<LLUICtrl>("day_pause_clouds");
    mRestoreEnvironment = findChild<LLUICtrl>("day_restore_environment");
    mDayPresets = { findChild<LLUICtrl>("day_sunrise"), findChild<LLUICtrl>("day_noon"),
                    findChild<LLUICtrl>("day_sunset"), findChild<LLUICtrl>("day_midnight") };

    // The section switches drive LLPipeline::sGradeBypassMask, which is
    // session state with no setting behind it, so every panel showing them
    // follows the mask (refreshSectionSwitches) rather than a binding.
    static const std::pair<const char*, U32> switches[] = {
        { "section_basic",     LLPipeline::GRADE_BYPASS_BASIC },
        { "section_primaries", LLPipeline::GRADE_BYPASS_PRIMARIES },
        { "section_split",     LLPipeline::GRADE_BYPASS_SPLIT },
        { "section_lut",       LLPipeline::GRADE_BYPASS_LUT },
        { "section_curve",     LLPipeline::GRADE_BYPASS_CURVE },
    };
    for (const auto& sw : switches)
    {
        if (LLUICtrl* ctrl = findChild<LLUICtrl>(sw.first))
        {
            mSectionSwitches.emplace_back(ctrl, sw.second);
        }
    }

    SLPhotoStudioDirectory::collectVec3Controls(this, mVec3Rows);
    for (const auto& row : mVec3Rows)
    {
        const std::string& setting = row.first;
        LLControlVariable* controlp = gSavedSettings.getControl(setting);
        if (!controlp)
        {
            LL_WARNS() << "Vec3 row bound to unknown setting: " << setting << LL_ENDL;
            continue;
        }
        mVec3Connections.emplace_back(controlp->getSignal()->connect(
            [this, setting](LLControlVariable*, const LLSD&, const LLSD&) { refreshVec3Row(setting); }));
        refreshVec3Row(setting);
    }

    setupToneCurve();
    setupSplitToneGraph();

    // Which sections this panel shows, and which the renderer's mode hides.
    applySectionFilter();
    fitSections();

    refreshReferenceRow();
    refreshCamReadouts();
    refreshSectionSwitches();

    return LLPanel::postBuild();
}

void SLPanelPhotoStudioSection::draw()
{
    // Polled: none of these has a setting signal to hang a refresh on. A
    // still arrives when a frame renders, the Develop menu flips the overlay
    // flags, the bypass mask has no setting, and the day cycle runs on the
    // clock. Each refresh does nothing unless what it shows has changed.
    refreshReferenceRow();
    refreshCamReadouts();
    refreshDayCycleRow();
    refreshSectionSwitches();

    if (LLView* lit = mLitCaption.get())
    {
        if (mLitTimer.getElapsedTimeF32() > LIT_CAPTION_SECONDS)
        {
            if (LLTextBox* box = dynamic_cast<LLTextBox*>(lit))
            {
                box->setHighlighted(false);
            }
            mLitCaption.markDead();
        }
    }

    LLPanel::draw();
}

// static
void SLPanelPhotoStudioSection::populateLUTCombo(LLComboBox* combo)
{
    if (!combo)
    {
        return;
    }

    // Only what the renderer's LUT loader can read: anything else in the
    // folder -- a readme, a subfolder, a stray .bak -- would be an entry that
    // fails at apply time with nothing but a log line to say why.
    // getExtension lowercases, so a .CUBE passes here as it does there.
    static const std::vector<std::string> extensions = { "cube", "tga", "png", "jpg", "jpeg", "bmp", "webp" };
    static const std::string dir_name = "colorlut";

    auto collect_from = [](const std::string& scan_dir)
    {
        std::vector<std::pair<std::string, std::string>> found; // stem, filename

        std::error_code ec;
        std::filesystem::path scan_path = fsyspath(scan_dir);
        if (!std::filesystem::is_directory(scan_path, ec) || ec)
        {
            return found;
        }

        // increment(ec), not ++: the throwing increment would carry a
        // transient filesystem error out through postBuild.
        std::filesystem::directory_iterator end;
        for (std::filesystem::directory_iterator entry(scan_path, ec); entry != end && !ec; entry.increment(ec))
        {
            std::error_code entry_ec;
            if (!entry->is_regular_file(entry_ec) || entry_ec)
            {
                continue;
            }
#if LL_WINDOWS
            std::string entry_stem = ll_convert_wide_to_string(entry->path().stem().native());
            std::string entry_filename = ll_convert_wide_to_string(entry->path().filename().native());
#else
            std::string entry_stem = entry->path().stem().native();
            std::string entry_filename = entry->path().filename().native();
#endif
            const std::string exten = gDirUtilp->getExtension(entry_filename);
            if (std::find(extensions.begin(), extensions.end(), exten) == extensions.end())
            {
                continue;
            }
            found.emplace_back(std::move(entry_stem), std::move(entry_filename));
        }
        if (ec)
        {
            LL_WARNS() << "Error reading LUT directory " << scan_dir << ": " << ec.message() << LL_ENDL;
        }
        return found;
    };

    // Nothing is bundled (#676): only the user's own LUTs are listed.
    const auto user_entries = collect_from(gDirUtilp->getExpandedFilename(LL_PATH_USER_SETTINGS, dir_name));
    for (const auto& entry : user_entries)
    {
        combo->add(entry.first, entry.second);
    }

    // Migration: a saved name that is no longer on disk (a LUT that used to be
    // bundled, or a deleted user file) falls back to "None" quietly.
    {
        const std::string saved = gSavedSettings.getString("RenderColorGradeLUT");
        if (!saved.empty()
            && std::none_of(user_entries.begin(), user_entries.end(),
                            [&](const auto& e) { return e.second == saved; }))
        {
            gSavedSettings.setString("RenderColorGradeLUT", "");
        }
    }

    // Mandatory: the combo is allow_text_entry, so nothing else selects the
    // saved value when the panel is built.
    combo->selectByValue(gSavedSettings.getString("RenderColorGradeLUT"));
    combo->resetDirty();
}

void SLPanelPhotoStudioSection::onResetControlDefault(const LLSD& userdata)
{
    const std::string key = userdata.asString();
    if (SLFloaterPhotoStudio* floater = studio())
    {
        floater->resetSetting(key, mDirectory.captionFor(key));
    }
    else if (LLControlVariable* controlp = gSavedSettings.getControl(key))
    {
        controlp->resetToDefault(true);
    }
}

void SLPanelPhotoStudioSection::onResetSection(const LLSD& userdata)
{
    const std::string section = userdata.asString();
    if (section.empty())
    {
        return;
    }

    // Through this panel's directory, so a section shown twice resets from
    // the panel that was clicked and never reaches into the other.
    std::set<std::string> keys;
    const SLPhotoStudioDirectory::Section* mainp = mDirectory.section(section);
    if (mainp)
    {
        SLPhotoStudioDirectory::collectBoundKeys(mainp->mPanel, keys);
    }
    if (const SLPhotoStudioDirectory::Section* advp = mDirectory.section(section + "_adv"))
    {
        SLPhotoStudioDirectory::collectBoundKeys(advp->mPanel, keys);
    }

    const std::string title = mainp ? mainp->mTitle : section;
    if (SLFloaterPhotoStudio* floater = studio())
    {
        floater->resetSettings(keys, title);
    }
    else
    {
        for (const std::string& key : keys)
        {
            if (LLControlVariable* controlp = gSavedSettings.getControl(key))
            {
                controlp->resetToDefault(true);
            }
        }
    }
}

void SLPanelPhotoStudioSection::onToggleSection(LLUICtrl* ctrl, const LLSD& userdata)
{
    // Section id to bit. The grouping matches Reset All's, which walks
    // sec_<id> and sec_<id>_adv together.
    static const std::map<std::string, U32> bypass_bits = {
        { "basic",     LLPipeline::GRADE_BYPASS_BASIC },
        { "primaries", LLPipeline::GRADE_BYPASS_PRIMARIES },
        { "split",     LLPipeline::GRADE_BYPASS_SPLIT },
        { "lut",       LLPipeline::GRADE_BYPASS_LUT },
        { "curve",     LLPipeline::GRADE_BYPASS_CURVE },
    };
    const auto found = bypass_bits.find(userdata.asString());
    if (!ctrl || found == bypass_bits.end())
    {
        return;
    }

    // Ticked is the section switched on, so the bit -- which suppresses --
    // is set when the box is clear. Nothing is written to gSavedSettings:
    // every grading control is on the Looks whitelist, so a comparison built
    // out of one would mark the active Look dirty. The mask is worth one
    // viewing session, and Photo Studio clears it when it closes.
    if (ctrl->getValue().asBoolean())
    {
        LLPipeline::sGradeBypassMask &= ~found->second;
    }
    else
    {
        LLPipeline::sGradeBypassMask |= found->second;
    }
    mSectionSwitchMask = LLPipeline::sGradeBypassMask;

    if (SLFloaterPhotoStudio* floater = studio())
    {
        floater->refreshBypassTitle();
    }
}

void SLPanelPhotoStudioSection::refreshSectionSwitches()
{
    if (mSectionSwitches.empty() || mSectionSwitchMask == LLPipeline::sGradeBypassMask)
    {
        return;
    }
    mSectionSwitchMask = LLPipeline::sGradeBypassMask;
    for (const auto& [ctrl, bit] : mSectionSwitches)
    {
        ctrl->setValue(LLSD((mSectionSwitchMask & bit) == 0));
    }
}

void SLPanelPhotoStudioSection::onToggleHUDInfo(const LLSD& userdata)
{
    // The Develop menu's Advanced.ToggleHUDInfo is a menu listener, out of a
    // panel's reach, so the flags are flipped here directly.
    const std::string& which = userdata.asString();
    if (which == "fov")
    {
        gDisplayFOV = !gDisplayFOV;
    }
    else if (which == "camera")
    {
        gDisplayCameraPos = !gDisplayCameraPos;
    }
    mCamReadoutState = -1;
    refreshCamReadouts();
}

void SLPanelPhotoStudioSection::refreshCamReadouts()
{
    if (!mCamShowFOV && !mCamShowPosition)
    {
        return;
    }
    // Polled, because the Develop menu flips the same flags and tells no one.
    const S32 state = (gDisplayFOV ? 1 : 0) | (gDisplayCameraPos ? 2 : 0);
    if (state == mCamReadoutState)
    {
        return;
    }
    mCamReadoutState = state;
    if (mCamShowFOV)
    {
        mCamShowFOV->setValue(LLSD((state & 1) != 0));
    }
    if (mCamShowPosition)
    {
        mCamShowPosition->setValue(LLSD((state & 2) != 0));
    }
}

void SLPanelPhotoStudioSection::refreshReferenceRow()
{
    if (!mReferenceClear && !mReferenceMode && !mReferencePosition)
    {
        return;
    }
    // Whether a still exists is render state, not a setting: a grab is only
    // serviced when the frame renders, and a resize drops the still.
    const bool have_still = gPipeline.hasReferenceStill();
    const S32  mode = gSavedSettings.getS32("RenderReferenceWipeMode");

    // Only the wipe has a movable seam; side by side is always centred.
    const S32 state = (have_still ? 1 : 0) | ((have_still && mode == 1) ? 2 : 0);
    if (state == mReferenceRowState)
    {
        return;
    }
    mReferenceRowState = state;

    if (mReferenceClear)
    {
        mReferenceClear->setEnabled(have_still);
    }
    if (mReferenceMode)
    {
        mReferenceMode->setEnabled(have_still);
    }
    if (mReferencePosition)
    {
        mReferencePosition->setEnabled((state & 2) != 0);
    }
}

void SLPanelPhotoStudioSection::refreshDayCycleRow()
{
    if (!mDayFreeze)
    {
        return; // not on this page
    }
    SLFloaterPhotoStudio* floater = studio();
    if (!floater)
    {
        return;
    }
    const SLFloaterPhotoStudio::DayCycleState& day = floater->getDayCycleState();

    // While the sky runs, the slider shows where it is, so ticking Freeze
    // holds the moment being looked at rather than jumping.
    if (!day.mFrozen && mDayTime)
    {
        mDayTime->setValue(day.mPosition);
    }

    const S32 state = (day.mCanChange ? 1 : 0) | (day.mFrozen ? 2 : 0) | (day.mHasDay ? 4 : 0)
                    | (day.mCloudsPaused ? 8 : 0)
                    | (day.mPresent[0] ? 16 : 0) | (day.mPresent[1] ? 32 : 0)
                    | (day.mPresent[2] ? 64 : 0) | (day.mPresent[3] ? 128 : 0);
    if (state == mDayCycleRowState)
    {
        return;
    }
    mDayCycleRowState = state;

    if (mCloudScroll)
    {
        mCloudScroll->setValue(day.mCloudsPaused);
    }
    // @setenv is enforced inside LLEnvironment, not here, so without this
    // the controls would look live and do nothing under a restriction.
    mDayFreeze->setEnabled(day.mCanChange && day.mHasDay);
    mDayFreeze->setValue(day.mFrozen);
    if (mDayTime)
    {
        mDayTime->setEnabled(day.mCanChange && day.mFrozen && day.mHasDay);
        if (day.mFrozen)
        {
            mDayTime->setValue(day.mPosition);
        }
    }
    if (mRestoreEnvironment)
    {
        mRestoreEnvironment->setEnabled(day.mCanChange && day.mFrozen);
    }
    for (size_t i = 0; i < mDayPresets.size(); ++i)
    {
        if (mDayPresets[i])
        {
            mDayPresets[i]->setEnabled(day.mCanChange && day.mHasDay && day.mPresent[i]);
        }
    }
}

