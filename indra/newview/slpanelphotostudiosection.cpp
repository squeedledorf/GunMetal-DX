void SLPanelPhotoStudioSection::refreshSplitToneGraph()
{
    if (!mSplitToneGraph || mSplitToneUpdating)
    {
        return;
    }

    const F32 mid = SLCurveModel::splitToneMid(gSavedSettings.getF32(SPLIT_TONE_BALANCE));
    const F32 amount     = llclamp(gSavedSettings.getF32(SPLIT_TONE_AMOUNT), 0.f, 1.f);
    const F32 mid_amount = llclamp(gSavedSettings.getF32(SPLIT_TONE_MIDTONE_AMOUNT), 0.f, 1.f);
    // Not clamped to the slider range: the model floors a width the way the
    // renderer does, so the bands show what is actually being applied.
    const F32 ws = gSavedSettings.getF32(SPLIT_TONE_SHADOW_WIDTH);
    const F32 wh = gSavedSettings.getF32(SPLIT_TONE_HIGHLIGHT_WIDTH);

    // A band wears the tint it applies, normalised the way the renderer
    // normalises it, so a tint that is merely bright reads as neutral.
    auto band_color = [](const char* key, F32 strength)
    {
        const LLColor3 tint = gSavedSettings.getColor3(key);
        constexpr F32 LUMA_R = 0.2126f, LUMA_G = 0.7152f, LUMA_B = 0.0722f;
        const F32 luma = llmax(tint.mV[0] * LUMA_R + tint.mV[1] * LUMA_G + tint.mV[2] * LUMA_B, 1e-4f);

        // Half brightness so a neutral band is mid grey and a saturated one
        // has room to read as itself without clipping to white.
        constexpr F32 DISPLAY_LEVEL = 0.5f;
        LLColor4 out(llclamp(tint.mV[0] / luma * DISPLAY_LEVEL, 0.f, 1.f),
                     llclamp(tint.mV[1] / luma * DISPLAY_LEVEL, 0.f, 1.f),
                     llclamp(tint.mV[2] / luma * DISPLAY_LEVEL, 0.f, 1.f),
                     1.f);
        // Alpha follows the amount, and never reaches zero: where the bands
        // lie is worth seeing even when nothing is being applied.
        out.mV[VALPHA] = 0.16f + 0.44f * strength;
        return out;
    };

    mSplitToneGraph->clearFillCurves();
    mSplitToneGraph->addFillCurve(
        [mid, ws, wh](F32 l) { return SLCurveModel::splitToneWeights(l, mid, ws, wh).mShadow; },
        band_color(SPLIT_TONE_SHADOW, amount));
    mSplitToneGraph->addFillCurve(
        [mid, ws, wh](F32 l) { return SLCurveModel::splitToneWeights(l, mid, ws, wh).mMidtone; },
        band_color(SPLIT_TONE_MIDTONE, mid_amount));
    mSplitToneGraph->addFillCurve(
        [mid, ws, wh](F32 l) { return SLCurveModel::splitToneWeights(l, mid, ws, wh).mHighlight; },
        band_color(SPLIT_TONE_HIGHLIGHT, amount));

    // Three handles along the top edge, held to the horizontal. Balance first,
    // so a tie in the hit test goes to the split point.
    SLCurveEditorCtrl::Handle balance;
    balance.mName = "balance";
    balance.mX = mid;
    balance.mY = 1.f;
    balance.mLockY = true;

    // The edges sit where the shadow band starts to fall away and where the
    // highlight band reaches full strength. A ramp that runs off the plot has
    // its handle held at the edge, locked and dimmed: the slider is the
    // control for that case, and the commit refuses a locked handle.
    auto edge_handle = [&band_color, amount](const char* name, F32 true_x, const char* tint_key)
    {
        SLCurveEditorCtrl::Handle h;
        h.mName = name;
        h.mX = llclamp(true_x, 0.f, 1.f);
        h.mY = 1.f;
        h.mLockY = true;
        const bool parked = (true_x < 0.f || true_x > 1.f);
        h.mLockX = parked;
        h.mColor = band_color(tint_key, amount);
        h.mColor.mV[VALPHA] = parked ? 0.5f : 1.f;
        return h;
    };
    const F32 ws_drawn = llmax(ws, SLCurveModel::SPLIT_TONE_MIN_WIDTH);
    const F32 wh_drawn = llmax(wh, SLCurveModel::SPLIT_TONE_MIN_WIDTH);

    mSplitToneGraph->setHandles({ balance,
                                  edge_handle("shadow_edge", mid - ws_drawn, SPLIT_TONE_SHADOW),
                                  edge_handle("highlight_edge", mid + wh_drawn, SPLIT_TONE_HIGHLIGHT) });
}

void SLPanelPhotoStudioSection::onCommitSplitToneGraph()
{
    // Only a drag means anything here.
    if (!mSplitToneGraph || mSplitToneGraph->getAction() != SLCurveEditorCtrl::ACTION_DRAG)
    {
        return;
    }
    const S32 index = mSplitToneGraph->getActiveHandle();
    if (index < 0 || index >= (S32)mSplitToneGraph->getHandles().size())
    {
        return;
    }
    const SLCurveEditorCtrl::Handle handle = mSplitToneGraph->getHandles()[index];
    const F32 mid = SLCurveModel::splitToneMid(gSavedSettings.getF32(SPLIT_TONE_BALANCE));

    // One setting per handle, so a drag is one undo step. A dragged-past
    // value clamps and the refresh below puts the handle where the setting
    // landed. A handle held at the plot edge writes nothing.
    {
        ScopedTrue updating(mSplitToneUpdating);
        if (handle.mName == "balance")
        {
            gSavedSettings.setF32(SPLIT_TONE_BALANCE, SLCurveModel::splitToneBalance(handle.mX));
        }
        else if (handle.mName == "shadow_edge" && !handle.mLockX)
        {
            F32 lo, hi;
            widthRange(mSplitShadowWidthSlider, lo, hi);
            gSavedSettings.setF32(SPLIT_TONE_SHADOW_WIDTH, llclamp(mid - handle.mX, lo, hi));
        }
        else if (handle.mName == "highlight_edge" && !handle.mLockX)
        {
            F32 lo, hi;
            widthRange(mSplitHighlightWidthSlider, lo, hi);
            gSavedSettings.setF32(SPLIT_TONE_HIGHLIGHT_WIDTH, llclamp(handle.mX - mid, lo, hi));
        }
    }
    refreshSplitToneGraph();
}

