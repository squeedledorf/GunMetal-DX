SLPhotoStudioSlot::SLPhotoStudioSlot(SLFloaterPhotoStudio* studio, S32 index, bool in_pane)
:   LLPanel(),
    mIndex(index),
    mInPane(in_pane)
{
    if (studio)
    {
        mStudio = studio->getHandle();
    }
}

SLPhotoStudioSlot::~SLPhotoStudioSlot()
{
}

SLFloaterPhotoStudio* SLPhotoStudioSlot::studio() const
{
    return dynamic_cast<SLFloaterPhotoStudio*>(mStudio.get());
}

bool SLPhotoStudioSlot::build()
{
    return buildFromFile("panel_photo_studio_slot.xml");
}

bool SLPhotoStudioSlot::postBuild()
{
    mSectionCombo = getChild<LLComboBox>("section_combo");
    mPopOutButton = getChild<LLButton>("pop_out");
    mBody = getChild<LLPanel>("slot_body");
    mPoppedNote = getChildView("popped_note");
    mPutBack = getChildView("put_back");

    mSectionCombo->setCommitCallback([this](LLUICtrl*, const LLSD&) { onSectionPicked(); });
    mPopOutButton->setCommitCallback([this](LLUICtrl*, const LLSD&) { onPopOutClicked(); });
    if (LLButton* put_back = dynamic_cast<LLButton*>(mPutBack))
    {
        put_back->setCommitCallback([this](LLUICtrl*, const LLSD&)
        {
            if (SLFloaterPhotoStudio* floater = studio())
            {
                floater->putBack(mIndex);
            }
        });
    }

    if (mInPane)
    {
        // Out in a window of its own, the button brings it back.
        mPopOutButton->setImageOverlay("Conv_toolbar_arrow_sw");
        mPopOutButton->setToolTip(getString("put_back_tooltip"));
    }
    return LLPanel::postBuild();
}

void SLPhotoStudioSlot::clearBody()
{
    mSection = nullptr;
    if (mBodyContent)
    {
        LLPanel* content = mBodyContent;
        mBodyContent = nullptr;
        if (gFocusMgr.childHasKeyboardFocus(content))
        {
            gFocusMgr.setKeyboardFocus(nullptr);
        }
        mBody->removeChild(content);
        delete content;
    }
}

void SLPhotoStudioSlot::setSection(const std::string& id, bool force)
{
    const SLPhotoStudioSectionDef* def = SLPhotoStudioSections::find(id);
    if (!def)
    {
        def = SLPhotoStudioSections::page("look");
    }
    if (!def || !mBody)
    {
        return;
    }
    if (def->mId == mSectionId && !force && (mBodyContent || mPoppedOut))
    {
        return;
    }
    mSectionId = def->mId;
    if (mSectionCombo)
    {
        mSectionCombo->selectByValue(mSectionId);
    }

    clearBody();
    if (mPoppedOut)
    {
        return;
    }

    LLPanel* content = nullptr;
    if (def->isScopes())
    {
        SLPanelPhotoStudioScopes* scopes = new SLPanelPhotoStudioScopes();
        scopes->buildFromFile("panel_photo_studio_scopes.xml");
        content = scopes;
    }
    else if (def->isEffects())
    {
        SLPanelPhotoStudioEffects* effects = new SLPanelPhotoStudioEffects(studio());
        effects->buildFromFile("panel_photo_studio_effects.xml");
        content = effects;
    }
    else
    {
        SLPanelPhotoStudioSection* section = new SLPanelPhotoStudioSection(studio(), *def);
        section->build();
        mSection = section;
        content = section;
    }

    // The body's size, following it: the section's accordion scrolls within.
    // setShape, not setRect + reshape: reshape only lays children out by the
    // change in size, so the page has to be built at its XUI size and then
    // reshaped to the body for its accordion to follow.
    content->setFollowsAll();
    mBody->addChild(content);
    content->setShape(mBody->getLocalRect());
    mBodyContent = content;
}

void SLPhotoStudioSlot::setPoppedOut(bool popped)
{
    if (mInPane || popped == mPoppedOut)
    {
        return;
    }
    mPoppedOut = popped;
    if (mBody)
    {
        mBody->setVisible(!popped);
    }
    if (mPoppedNote)
    {
        mPoppedNote->setVisible(popped);
    }
    if (mPutBack)
    {
        mPutBack->setVisible(popped);
    }
    // The window has its own dropdown while it is out.
    if (mSectionCombo)
    {
        mSectionCombo->setEnabled(!popped);
    }
    if (mPopOutButton)
    {
        mPopOutButton->setEnabled(!popped);
    }

    if (popped)
    {
        clearBody();
    }
    else
    {
        setSection(mSectionId, true);
    }
}

std::string SLPhotoStudioSlot::getSectionLabel() const
{
    return mSectionCombo ? mSectionCombo->getSelectedItemLabel() : mSectionId;
}

void SLPhotoStudioSlot::focusSectionCombo()
{
    if (mSectionCombo && mSectionCombo->getEnabled())
    {
        mSectionCombo->setFocus(true);
    }
}

bool SLPhotoStudioSlot::hasKeyboardFocusInside() const
{
    return gFocusMgr.childHasKeyboardFocus(this);
}

void SLPhotoStudioSlot::onSectionPicked()
{
    if (!mSectionCombo)
    {
        return;
    }
    const std::string id = mSectionCombo->getValue().asString();
    setSection(id);
    if (SLFloaterPhotoStudio* floater = studio())
    {
        floater->onSlotSectionChanged(mIndex, mSectionId);
    }
}

void SLPhotoStudioSlot::onPopOutClicked()
{
    SLFloaterPhotoStudio* floater = studio();
    if (!floater)
    {
        return;
    }
    if (mInPane)
    {
        floater->putBack(mIndex);
    }
    else
    {
        floater->popOut(mIndex);
    }
}
