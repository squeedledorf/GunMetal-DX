#ifndef SL_SLUPDATEVERIFY_H
#define SL_SLUPDATEVERIFY_H

#include <string>

// The update signing PUBLIC key: 64 hex characters (the raw 32-byte Ed25519 key).
// Generated by the owner with scripts/updater/gen_update_key.sh; the private key never
// enters git. While this is empty (the placeholder) the updater refuses every manifest,
// so a build without the real key can never install anything. Builds can set it with
// -DSLIPSTREAM_UPDATE_PUBKEY_HEX=\"...\" (CI does, from the repository variable
// UPDATE_PUBKEY_HEX), or edit the constant once the key exists.
#ifndef SLIPSTREAM_UPDATE_PUBKEY_HEX
#define SLIPSTREAM_UPDATE_PUBKEY_HEX ""
#endif

// Domain separator: the signed message is this prefix followed by the manifest bytes, so
// a signature made for another purpose with the same key is never a valid manifest.
#define SLIPSTREAM_UPDATE_SIGN_PREFIX "slipstream-update-v1\n"

namespace SLUpdateVerify
{
    // Decoders for the strings in the feed. False on malformed input.
    bool hexDecode(const std::string& hex, std::string& out);
    bool base64Decode(const std::string& text, std::string& out);

    // True when pubkey_hex is a valid 64-hex Ed25519 key (i.e. the build has a real key).
    // `pubkey_hex` nullptr = the key compiled into this build (what the viewer always uses);
    // an explicit string (even "") is for tests and the signing tools.
    bool keyConfigured(const char* pubkey_hex = nullptr);

    // Verifies base64 `signature_b64` over SLIPSTREAM_UPDATE_SIGN_PREFIX + manifest with the
    // given public key. False for any failure, including an unconfigured key.
    bool verifyManifest(const std::string& manifest, const std::string& signature_b64,
                        const char* pubkey_hex = nullptr);

    // Lower-case hex SHA-256 of a file; empty string if it cannot be read. `size_out`
    // receives the byte count read.
    std::string sha256File(const std::string& path, unsigned long long* size_out = nullptr);

    // Constant-time comparison of two hex digests (case-insensitive).
    bool sameDigest(const std::string& a, const std::string& b);
}

#endif // SL_SLUPDATEVERIFY_H
