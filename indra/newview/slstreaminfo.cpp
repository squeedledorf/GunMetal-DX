SLStreamInfo::SLStreamInfo()
{
    if (gAudiop && gAudiop->getStreamingAudioImpl() && gAudiop->getStreamingAudioImpl()->supportsMetaData())
    {
        mMetadataConnection = gAudiop->getStreamingAudioImpl()->setMetadataUpdatedCallback([this](const LLSD& metadata) { handleMetadataUpdate(metadata); });
    }
}

SLStreamInfo::~SLStreamInfo()
{
    if (mMetadataConnection.connected())
    {
        mMetadataConnection.disconnect();
    }
}

void SLStreamInfo::handleMetadataUpdate(const LLSD& metadata)
{
    static LLCachedControl<bool> show_stream_info(gSavedSettings, "ShowStreamInfo", false);
    if (!show_stream_info) return;

    bool stream_info_to_chat = gSavedSettings.getBOOL("ShowStreamInfoToChat");

    LLFloater* music_ticker = LLFloaterReg::findInstance("music_ticker");
    if (!stream_info_to_chat && music_ticker)
        return;

    if (metadata.size() > 0)
    {
        std::string station = metadata.has("TRSN") ? metadata["TRSN"].asString() : metadata.has("icy-name") ? metadata["icy-name"].asString() : LLTrans::getString("NowPlaying");
        // Some stations get a little ridiculous with the length.
        if (station.length() > 64)
        {
            LLStringUtil::truncate(station, 64);
            station.append("...");
        }
        LLSD args;
        LLSD payload;
        args["STATION"] = station;
        // Stream tags are whatever the stream's operator says: kept short.
        auto capped = [](std::string text) { if (text.size() > 256) { text.resize(256); } return text; };
        std::stringstream info;
        if (metadata.has("TITLE"))
            info << capped(metadata["TITLE"].asString());
        if (metadata.has("TITLE") && metadata.has("ARTIST"))
            info << "\n";
        if (metadata.has("ARTIST"))
            info << capped(metadata["ARTIST"].asString());
        // Shown (and possibly sent to chat) without turning anything in it into links.
        std::string info_text = info.str();
        for (const char* tag : { "<nolink>", "</nolink>" })
        {
            std::string lower = info_text;
            LLStringUtil::toLower(lower);
            for (size_t at = lower.find(tag); at != std::string::npos; at = lower.find(tag))
            {
                info_text.erase(at, strlen(tag));
                lower.erase(at, strlen(tag));
            }
        }
        args["INFO"] = info_text.empty() ? info_text : "<nolink>" + info_text + "</nolink>";

        const std::string station_url = stationURL(metadata);

        LLNotification::Params notify_params;
        notify_params.name = "StreamInfo";
        notify_params.substitutions = args;
        if (!station_url.empty())
        {
            notify_params.payload = payload.with("respond_on_mousedown", TRUE);

            LLNotification::Params::Functor functor_p;
            functor_p.function = [=](const LLSD&, const LLSD&) { openStationURL(station_url); };
            notify_params.functor = functor_p;
        }
        else
        {
            notify_params.payload = payload;
        }

        notify_params.force_to_chat = stream_info_to_chat;
        LLNotificationPtr notification = LLNotifications::instance().add(notify_params);
    }
}

// static
std::string SLStreamInfo::stationURL(const LLSD& metadata)
{
    std::string url = metadata.has("URL") ? metadata["URL"].asString()
                    : metadata.has("icy-url") ? metadata["icy-url"].asString() : std::string();
    LLStringUtil::trim(url);
    if (url.size() > 1024)
        return std::string();
    for (unsigned char c : url)
    {
        if (c < 0x21 || c == 0x7f)
            return std::string();
    }
    std::string lower = url;
    LLStringUtil::toLower(lower);
    if (lower.compare(0, 7, "http://") != 0 && lower.compare(0, 8, "https://") != 0)
        return std::string();
    return url;
}

// static
void SLStreamInfo::openStationURL(const std::string& url)
{
    if (!url.empty())
        LLWeb::loadURL(url, LLStringUtil::null, LLStringUtil::null, /*from_web_content=*/true);
}
