/// What a panel's dropdown can show: a whole page of sections, a few of its
/// sections, or the scopes. The ids are saved (SLPhotoStudioPanels), so never
/// change one; add new ones instead.
struct SLPhotoStudioSectionDef
{
    std::string              mId;
    /// The page the sections come from: "look", "lens", "scene", "sky", "cam",
    /// or "scopes" or "effects", which have no sections (each is a panel
    /// class of its own).
    std::string              mPage;
    /// The section panels ("sec_dof", ...) shown, each with its "_adv"
    /// sibling if it has one; empty for the whole page.
    std::vector<std::string> mSections;

    bool isScopes() const { return mPage == "scopes"; }
    /// The FX stack (SLPanelPhotoStudioEffects).
    bool isEffects() const { return mPage == "effects"; }
    bool isWholePage() const { return mSections.empty(); }
    /// Whether this shows @a section_name of @a page.
    bool shows(const std::string& page, const std::string& section_name) const;
    /// The XUI file the page is built from.
    std::string fileName() const;
};

namespace SLPhotoStudioSections
{
/// Every section, in dropdown order.
const std::vector<SLPhotoStudioSectionDef>& all();
/// By id, or null.
const SLPhotoStudioSectionDef* find(const std::string& id);
/// The whole-page section for @a page, or null.
const SLPhotoStudioSectionDef* page(const std::string& page);
/// The pages that have sections, in order: look, lens, scene, sky, cam.
const std::vector<std::string>& pages();
/// False for a section the renderer's mode hides: Bloom and Cross Filter
/// without HDR, the legacy Glow with it.
bool shownForRenderer(const std::string& section_name);
}

/**
 * A section panel: one page XUI (panel_photo_studio_<page>.xml), showing all
 * of its accordion sections or only some, with everything that is not a plain
 * settings binding wired up for this instance.
 *
 * Several of these may be alive for the same page at once -- two panels can
 * show the same section, a popped-out window builds its own, and the floater
 * builds every page once for its Find catalog -- so nothing here is shared
 * through widget names: each instance keeps its own directory of what it
 * holds. Settings-bound widgets keep each other in step through the settings;
 * the few that are not bound (the vector rows, the graphs, the section
 * switches, the reference and day cycle rows) follow their settings or poll
 * the state they show, so every instance stays current.
 */
class SLPanelPhotoStudioSection final : public LLPanel
{
public:
    SLPanelPhotoStudioSection(SLFloaterPhotoStudio* studio, const SLPhotoStudioSectionDef& def);
    ~SLPanelPhotoStudioSection() override;

    /// Build from the page's XUI. False if the file could not be built.
    bool build();

    bool postBuild() override;
    void draw() override;

    const SLPhotoStudioSectionDef& getDef() const { return mDef; }
    const SLPhotoStudioDirectory& getDirectory() const { return mDirectory; }

    /// Go to a section (@a key empty) or a setting in it: its accordion tab
    /// opened and scrolled to, the setting given the keyboard and its caption
    /// lit for a moment. False when this panel does not show it.
    bool showTarget(const std::string& section_name, const std::string& key);

    /// Fill a LUT dropdown with the user's own LUTs (none are bundled).
    static void populateLUTCombo(LLComboBox* combo);

private:
    SLFloaterPhotoStudio* studio() const;

    // --- Callbacks the page XUI names (PhotoStudio.*) ---
    void onResetControlDefault(const LLSD& userdata);
    void onResetSection(const LLSD& userdata);
    void onToggleSection(LLUICtrl* ctrl, const LLSD& userdata);
    void onCommitVec3(LLUICtrl* ctrl);
    void onCommitToneCurve();
    void onClickResetToneCurveChannel();
    void onToneCurvePreset(const LLSD& userdata);
    void onCommitSplitToneGraph();
    void onToggleHUDInfo(const LLSD& userdata);
    void onToggleDayFreeze(LLUICtrl* ctrl);
    void onCommitDayTime(LLUICtrl* ctrl);
    void onClickDayPreset(const LLSD& userdata);
    void onToggleCloudScroll(LLUICtrl* ctrl);

    // --- Keeping this instance's widgets current ---
    void applySectionFilter();
    void refreshBloomSections();
    void updateTonemapperRows();
    void refreshVec3Row(const std::string& setting_name);
    void setupToneCurve();
    void refreshToneCurve();
    S32  getToneCurveChannel() const;
    void setupSplitToneGraph();
    void refreshSplitToneGraph();
    void refreshReferenceRow();
    void refreshCamReadouts();
    void refreshDayCycleRow();
    void refreshSectionSwitches();
    void fitSections();

    LLHandle<LLFloater> mStudio;
    SLPhotoStudioSectionDef mDef;
    SLPhotoStudioDirectory mDirectory;

    /// The caption a jump lit, and how long ago; draw() puts it out.
    LLHandle<LLView> mLitCaption;
    LLFrameTimer mLitTimer;

    struct TonemapperRow
    {
        S32 mType = 0;
        LLUICtrl* mCtrl = nullptr;
        LLUICtrl* mReset = nullptr;
    };
    std::vector<TonemapperRow> mTonemapperRows;
    boost::signals2::scoped_connection mTonemapConnection;
    boost::signals2::scoped_connection mHDRConnection;

    /// Spinner (or slider) triplets named "vec3_<Setting>_<0|1|2>".
    std::map<std::string, std::array<LLUICtrl*, 3>> mVec3Rows;
    std::vector<boost::signals2::scoped_connection> mVec3Connections;
    bool mVec3Updating = false;

    std::vector<boost::signals2::scoped_connection> mToneCurveConnections;
    SLCurveEditorCtrl* mToneCurve = nullptr;
    LLComboBox* mToneCurveChannel = nullptr;
    bool mToneCurveUpdating = false;

    std::vector<boost::signals2::scoped_connection> mSplitToneConnections;
    SLCurveEditorCtrl* mSplitToneGraph = nullptr;
    LLSliderCtrl* mSplitShadowWidthSlider = nullptr;
    LLSliderCtrl* mSplitHighlightWidthSlider = nullptr;
    bool mSplitToneUpdating = false;

    /// The per-section "Apply" boxes (no control_name: session state), by
    /// the LLPipeline::sGradeBypassMask bit each drives.
    std::vector<std::pair<LLUICtrl*, U32>> mSectionSwitches;
    U32 mSectionSwitchMask = ~0u;

    LLUICtrl* mReferenceClear = nullptr;
    LLUICtrl* mReferenceMode = nullptr;
    LLUICtrl* mReferencePosition = nullptr;
    S32 mReferenceRowState = -1;

    LLUICtrl* mCamShowFOV = nullptr;
    LLUICtrl* mCamShowPosition = nullptr;
    S32 mCamReadoutState = -1;

    LLUICtrl* mDayFreeze = nullptr;
    LLUICtrl* mDayTime = nullptr;
    LLUICtrl* mCloudScroll = nullptr;
    LLUICtrl* mRestoreEnvironment = nullptr;
    std::array<LLUICtrl*, 4> mDayPresets = {};
    S32 mDayCycleRowState = -1;
};

/**
 * One Photo Studio panel: the section dropdown and pop-out button over the
 * section it shows. Lives in the floater's grid, or alone in a popped-out
 * window (SLFloaterPhotoStudioPane), where the pop-out button puts it back.
 */
class SLPhotoStudioSlot final : public LLPanel
{
public:
    SLPhotoStudioSlot(SLFloaterPhotoStudio* studio, S32 index, bool in_pane);
    ~SLPhotoStudioSlot() override;

    /// Build from panel_photo_studio_slot.xml.
    bool build();
    bool postBuild() override;

    S32 getIndex() const { return mIndex; }
    const std::string& getSectionId() const { return mSectionId; }
    /// What the dropdown calls it ("Lens: Depth of Field").
    std::string getSectionLabel() const;
    /// Show @a id (an unknown id shows the Look). Rebuilds the body only
    /// when the section changes, or when @a force.
    void setSection(const std::string& id, bool force = false);
    /// The section panel, or null while popped out or showing the scopes or
    /// the effects.
    SLPanelPhotoStudioSection* getSectionPanel() const { return mSection; }
    /// Whether the body holds a built section (or the scopes).
    bool hasContent() const { return mBodyContent != nullptr; }
    /// Drop what the body holds, keeping the section id: for a panel the
    /// layout no longer shows. setSection(id, true) builds it again.
    void releaseContent() { clearBody(); }

    /// In the floater's grid: whether the panel is out in a window of its
    /// own, in which case this shows a note and a way back instead.
    void setPoppedOut(bool popped);
    bool isPoppedOut() const { return mPoppedOut; }

    /// Ctrl+1..4: the keyboard to the section dropdown.
    void focusSectionCombo();
    bool hasKeyboardFocusInside() const;

private:
    SLFloaterPhotoStudio* studio() const;
    void onSectionPicked();
    void onPopOutClicked();
    void clearBody();

    LLHandle<LLFloater> mStudio;
    S32 mIndex = 0;
    bool mInPane = false;
    bool mPoppedOut = false;
    std::string mSectionId;

    LLComboBox* mSectionCombo = nullptr;
    LLButton* mPopOutButton = nullptr;
    LLPanel* mBody = nullptr;
    LLView* mPoppedNote = nullptr;
    LLView* mPutBack = nullptr;
    /// What the body holds: a section panel, or the scopes or the effects
    /// (panels of their own).
    SLPanelPhotoStudioSection* mSection = nullptr;
    LLPanel* mBodyContent = nullptr;
};

#endif // SL_PANELPHOTOSTUDIOSECTION_H
